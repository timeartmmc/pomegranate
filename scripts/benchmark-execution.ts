import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { promisify } from 'node:util';
import { QueryClient } from '@tanstack/query-core';
import { compile } from '../dist/index.js';
import {
  executionFixture,
  executionSelection,
} from '../test/execution-fixture.ts';
import { verifyExecutions } from '../test/execution-checks.ts';
import { generatedWorkspace } from '../test/generated-workspace.ts';

// Handwritten bindings use identical core guarantees, not a weaker happy-path
// fetch wrapper. This isolates the endpoint wiring supplied by the emitter.
// Query keys already existed before this milestone; no new key-factory deletion
// is attributed to executable clients. Timings are evidence, never CI thresholds.
const handwritten = `
import {operations} from './execution-generated/client.consumer.operations.ts';
import {defineCall} from './execution-generated/call-runtime.ts';
import {executionConfig} from './execution-generated/execution-runtime.ts';
import type {ClientConfig} from './execution-generated/execution-runtime.ts';
import type {ExecutionClient} from './execution-generated/call-runtime.ts';
export {operations};
export {RequestValidationError} from './execution-generated/runtime.ts';
export {ResponseError} from './execution-generated/execution-runtime.ts';
export function createClient(config: ClientConfig): ExecutionClient<typeof operations> {
  const runtime = executionConfig(config);
  const client = 'consumer';
  return Object.freeze({
    commandOptions: defineCall({operation: operations.commandOptions, operationId: 'commandOptions', ...runtime, client}),
    createWidget: defineCall({operation: operations.createWidget, operationId: 'createWidget', ...runtime, client}),
    health: defineCall({operation: operations.health, operationId: 'health', ...runtime, client}),
    listItems: defineCall({operation: operations.listItems, operationId: 'listItems', ...runtime, client}),
    listRecords: defineCall({operation: operations.listRecords, operationId: 'listRecords', ...runtime, client}),
    readItem: defineCall({operation: operations.readItem, operationId: 'readItem', ...runtime, client}),
    readMap: defineCall({operation: operations.readMap, operationId: 'readMap', ...runtime, client}),
    readOutcome: defineCall({operation: operations.readOutcome, operationId: 'readOutcome', ...runtime, client}),
    removeWidget: defineCall({operation: operations.removeWidget, operationId: 'removeWidget', ...runtime, client}),
    replaceWidget: defineCall({operation: operations.replaceWidget, operationId: 'replaceWidget', ...runtime, client}),
    write_options: defineCall({operation: operations.write_options, operationId: 'write_options', ...runtime, client}),
  });
}
`;
const generated = `export {createClient} from './execution-generated/client.consumer.ts';\n`;
const repo = dirname(dirname(fileURLToPath(import.meta.url)));
const document = executionFixture();
const files = await compile(document, executionSelection);
const without = await compile(document, {
  ...executionSelection,
  executionClients: [],
});
const baselineRef = process.argv[2] ?? 'HEAD';
const baselineRevision = (
  await promisify(execFile)('git', ['rev-parse', baselineRef], { cwd: repo })
).stdout.trim();
const oldRuntime = (
  await promisify(execFile)(
    'git',
    ['show', `${baselineRevision}:src/query-runtime.ts`],
    { cwd: repo, maxBuffer: 1024 * 1024 },
  )
).stdout;
const oldFiles: Record<string, string> = {
  ...without,
  'query-runtime.ts': `// Generated by Pomegranate. Do not edit.\n${oldRuntime}`,
};
// The pre-extraction runtime owns these primitives itself. A later baseline may
// already import the shared helper, so retain it when that baseline needs it.
if (!oldRuntime.includes("from './execution-runtime.ts'"))
  delete oldFiles['execution-runtime.ts'];
const coreOptions = { clients: ['consumer'], transportHeaders: ['X-Language'] };
const core = await compile(document, coreOptions);
const executionOnly = await compile(document, {
  ...coreOptions,
  executionClients: ['consumer'],
});
const bytes = (files: Readonly<Record<string, string>>) =>
  Object.values(files).reduce(
    (sum, source) => sum + Buffer.byteLength(source),
    0,
  );
const root = await generatedWorkspace(files, 'execution-generated');
let oldRoot: string | undefined;
try {
  oldRoot = await generatedWorkspace(oldFiles, 'before-generated');
  await writeFile(join(root, 'handwritten.ts'), handwritten);
  await writeFile(join(root, 'generated.ts'), generated);
  const typeTimes: Record<string, number[]> = {
    handwritten: [],
    generated: [],
  };
  for (const name of ['handwritten', 'generated'])
    await writeFile(
      join(root, `${name}.json`),
      JSON.stringify({
        compilerOptions: {
          target: 'ES2022',
          module: 'NodeNext',
          moduleResolution: 'NodeNext',
          strict: true,
          exactOptionalPropertyTypes: true,
          noUncheckedIndexedAccess: true,
          allowImportingTsExtensions: true,
          noEmit: true,
          types: ['node'],
          lib: ['ES2022', 'DOM'],
        },
        include: [`${name}.ts`],
      }),
    );
  for (let round = 0; round < 5; round++)
    for (const name of round % 2
      ? ['generated', 'handwritten']
      : ['handwritten', 'generated']) {
      const start = performance.now();
      await promisify(execFile)(
        process.execPath,
        [
          join(repo, 'node_modules/typescript/bin/tsc'),
          '-p',
          join(root, `${name}.json`),
        ],
        { cwd: root },
      );
      typeTimes[name]!.push(performance.now() - start);
    }
  type Module =
    typeof import('../test/.generated/execution/client.consumer.ts');
  const automatic = (await import(
    pathToFileURL(join(root, 'execution-generated/client.consumer.ts')).href
  )) as Module;
  const manual = (await import(
    pathToFileURL(join(root, 'handwritten.ts')).href
  )) as Module;
  const queries = (await import(
    pathToFileURL(join(root, 'execution-generated/client.consumer.queries.ts'))
      .href
  )) as typeof import('../test/.generated/execution/client.consumer.queries.ts');
  const staff = (await import(
    pathToFileURL(join(root, 'execution-generated/client.staff.ts')).href
  )) as typeof import('../test/.generated/execution/client.staff.ts');
  await verifyExecutions(manual, queries, staff);
  await verifyExecutions(automatic, queries, staff);
  const runtimeTimes: Record<string, number[]> = {
    handwritten: [],
    generated: [],
  };
  const config = {
    namespace: 'benchmark',
    execute: async () => ({
      status: 200,
      headers: { 'Content-Type': 'application/json' },
      body: '{"id":"item","label":"Synthetic"}',
    }),
  };
  const implementations = {
    handwritten: manual.createClient(config),
    generated: automatic.createClient(config),
  };
  const args = {
    context: { revision: 'one', locale: 'en' },
    input: { path: { id: 'item' } },
  };
  for (let round = 0; round < 10; round++)
    for (const name of round % 2
      ? (['generated', 'handwritten'] as const)
      : (['handwritten', 'generated'] as const)) {
      const start = performance.now();
      for (let iteration = 0; iteration < 2_000; iteration++)
        assert.equal(
          (await implementations[name].readItem.call(args)).data.label,
          'Synthetic',
        );
      if (round >= 2)
        runtimeTimes[name]!.push((performance.now() - start) / 2_000);
    }
  const median = (values: number[]) =>
    Number(
      [...values]
        .sort((a, b) => a - b)
        [Math.floor(values.length / 2)]!.toFixed(4),
    );
  const beforeQueries = (await import(
    pathToFileURL(join(oldRoot, 'before-generated/client.consumer.queries.ts'))
      .href
  )) as typeof queries;
  const cache = new QueryClient();
  const prepared = {
    before: beforeQueries.createQueries(config).readItem.options(args),
    after: queries.createQueries(config).readItem.options(args),
  };
  const queryTimes: Record<'before' | 'after', number[]> = {
    before: [],
    after: [],
  };
  try {
    for (let round = 0; round < 10; round++)
      for (const name of round % 2
        ? (['after', 'before'] as const)
        : (['before', 'after'] as const)) {
        const options = prepared[name];
        const execution = {
          client: cache,
          queryKey: options.queryKey,
          signal: new AbortController().signal,
          meta: undefined,
        };
        const start = performance.now();
        for (let iteration = 0; iteration < 2_000; iteration++)
          assert.equal(
            (await options.queryFn(execution)).data.label,
            'Synthetic',
          );
        if (round >= 2)
          queryTimes[name].push((performance.now() - start) / 2_000);
      }
  } finally {
    cache.clear();
  }
  console.log(
    JSON.stringify(
      {
        node: process.version,
        typescript: (
          await readFile(
            join(repo, 'node_modules/typescript/package.json'),
            'utf8',
          )
        ).match(/"version":\s*"([^"]+)"/)?.[1],
        equivalence:
          'both bindings passed all shared direct-call acceptance checks',
        handwrittenEndpointBindings: Object.keys(manual.operations).length,
        generatedApplicationEndpointBindings: 0,
        generatedApplicationKeyFactories: 0,
        keyFactoryChange: 'query key factories were already generated',
        queryBaselineRevision: baselineRevision,
        applicationPolicy:
          'same raw executor; application still owns credentials, attempts, deadlines, locale, sessions, file bodies and cache effects',
        generatedSourceBytes: bytes(files),
        addedSourceBytesWithQueries: bytes(files) - bytes(without),
        addedSourceBytesExecutionOnly: bytes(executionOnly) - bytes(core),
        queryRefactorSourceBytes: bytes(without) - bytes(oldFiles),
        handwrittenBindingBytes: Buffer.byteLength(handwritten),
        generatedApplicationBindingBytes: Buffer.byteLength(generated),
        medianTypecheckMs: Object.fromEntries(
          Object.entries(typeTimes).map(([name, times]) => [
            name,
            median(times),
          ]),
        ),
        medianCallMs: Object.fromEntries(
          Object.entries(runtimeTimes).map(([name, times]) => [
            name,
            median(times),
          ]),
        ),
        medianQueryExecutionMs: Object.fromEntries(
          Object.entries(queryTimes).map(([name, times]) => [
            name,
            median(times),
          ]),
        ),
      },
      null,
      2,
    ),
  );
} finally {
  await rm(root, { recursive: true, force: true });
  if (oldRoot) await rm(oldRoot, { recursive: true, force: true });
}
