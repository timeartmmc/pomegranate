import assert from 'node:assert/strict';
import test from 'node:test';
import { compile, ContractError } from '../dist/index.js';
import { invalidOptions } from './assertions.ts';
import { fixture, preparation } from './helpers.ts';
import type { Fixture } from './helpers.ts';

const operationLocation = 'paths./api/widgets/{widgetId}/preparations.post';
const selection = { clients: ['staff'] };

interface ArrayCase {
  name: string;
  values: (document: Fixture) => readonly unknown[];
  replace: (document: Fixture, values: unknown[]) => void;
  location: string;
  message: RegExp;
  indexed?: boolean;
}

const cases: ArrayCase[] = [
  ...(['surfaces', 'retry', 'timeout'] as const).map((field): ArrayCase => ({
    name: `policy ${field}`,
    values: (document) => document['x-pom-policy'][field],
    replace: (document, values) => {
      Object.assign(document['x-pom-policy'], { [field]: values });
    },
    location: `x-pom-policy.${field}`,
    message: /expected a nonempty string/,
    indexed: true,
  })),
  {
    name: 'operation surfaces',
    values: (document) => preparation(document)['x-pom'].surfaces,
    replace: (document, values) => {
      Object.assign(preparation(document)['x-pom'], { surfaces: values });
    },
    location: `${operationLocation}.x-pom.surfaces`,
    message: /expected a nonempty string/,
    indexed: true,
  },
  {
    name: 'parameters',
    values: (document) => preparation(document).parameters,
    replace: (document, values) => {
      Object.assign(preparation(document), { parameters: values });
    },
    location: `${operationLocation}.parameters`,
    message: /expected an object/,
    indexed: true,
  },
  {
    name: 'operation documentation tags',
    values: () => ['widgets'],
    replace: (document, values) => {
      Object.assign(preparation(document), { tags: values });
    },
    location: `${operationLocation}.tags`,
    message: /expected an array of nonempty documentation tags/,
  },
  {
    name: 'document documentation tags',
    values: () => [{ name: 'widgets' }],
    replace: (document, values) => {
      Object.assign(document, { tags: values });
    },
    location: 'tags',
    message: /expected an object/,
    indexed: true,
  },
  ...(['anyOf', 'oneOf'] as const).map((keyword): ArrayCase => ({
    name: `${keyword} branches in an unselected schema`,
    values: () => [{ type: 'null' }],
    replace: (document, values) => {
      Object.assign(document.components.schemas, {
        MissingBranch: { [keyword]: values },
      });
    },
    location: `components.schemas.MissingBranch.${keyword}`,
    message: /expected an object/,
    indexed: true,
  })),
];

function missingSlot(
  values: readonly unknown[],
  index: number,
  sparse: boolean,
): unknown[] {
  const result = [...values];
  result.splice(index, 0, undefined);
  if (sparse) Reflect.deleteProperty(result, index);
  return result;
}

for (const { name, values, replace, location, message, indexed } of cases) {
  for (const sparse of [false, true]) {
    for (const position of ['first', 'last']) {
      void test(`${name} diagnoses ${sparse ? 'a hole' : 'undefined'} in the ${position} slot before selecting clients`, async () => {
        const document = fixture();
        const original = values(document);
        const index = position === 'first' ? 0 : original.length;
        replace(document, missingSlot(original, index, sparse));
        const before = structuredClone(document);
        await assert.rejects(compile(document, selection), (error) => {
          assert.ok(error instanceof ContractError);
          assert.equal(
            error.location,
            indexed ? `${location}[${index}]` : location,
          );
          assert.match(error.message, message);
          return true;
        });
        assert.deepEqual(document, before);
      });
    }
  }
}

for (const sparse of [false, true]) {
  for (const position of ['first', 'last']) {
    void test(`client selection diagnoses ${sparse ? 'a hole' : 'undefined'} in the ${position} slot`, async () => {
      const index = position === 'first' ? 0 : 1;
      const clients = missingSlot(['consumer'], index, sparse);
      const document = fixture();
      await assert.rejects(
        invalidOptions(compile, document, { clients }),
        (error) => {
          assert.ok(error instanceof ContractError);
          assert.equal(error.location, `clients[${index}]`);
          assert.match(error.message, /expected a nonempty string/);
          return true;
        },
      );
    });
  }
}

void test('dense arrays and empty optional documentation arrays preserve generated bytes', async () => {
  const document = fixture();
  const expected = await compile(document, selection);
  Object.assign(document, {
    tags: [{ name: 'widgets', description: 'Synthetic' }],
  });
  Object.assign(preparation(document), { tags: ['widgets'] });
  Object.assign(document.components.schemas, {
    UnusedNullable: { anyOf: [{ type: 'null' }, { type: 'string' }] },
  });
  assert.deepEqual(await compile(document, selection), expected);
  Object.assign(document, { tags: [] });
  Object.assign(preparation(document), { tags: [] });
  assert.deepEqual(await compile(document, selection), expected);
});
