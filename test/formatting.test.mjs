import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { cp, mkdir, mkdtemp, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { promisify } from 'node:util';
import test from 'node:test';
import { compile, runProject } from '../dist/index.js';
import { fixture, temporary, fileSnapshot } from './helpers.mjs';

const exec = promisify(execFile);
const repo = dirname(dirname(fileURLToPath(import.meta.url)));

async function brokenCompiler(t) {
  const cache = join(repo, 'node_modules', '.cache');
  await mkdir(cache, { recursive: true });
  const root = await mkdtemp(join(cache, 'pom-format-failure-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await writeFile(join(root, 'package.json'), '{"type":"module"}\n');
  await cp(join(repo, 'dist'), join(root, 'dist'), { recursive: true });
  // Corrupt only this isolated compiler copy. The real formatter must report a
  // parse error while the remaining client modules can still format normally.
  await writeFile(join(root, 'dist/runtime.ts'), 'export const broken = ;\n');
  return import(pathToFileURL(join(root, 'dist/index.js')).href);
}

test('generated bytes ignore consumer formatter configuration and working directory', async (t) => {
  const root = await temporary(t);
  const document = fixture();
  await writeFile(join(root, 'openapi.json'), JSON.stringify(document));
  await writeFile(
    join(root, '.oxfmtrc.json'),
    JSON.stringify({
      singleQuote: false,
      semi: false,
      printWidth: 160,
      useTabs: true,
      sortImports: true,
    }),
  );
  await writeFile(
    join(root, 'oxfmt.config.ts'),
    'throw new Error("Consumer config must not execute");\n',
  );
  await writeFile(
    join(root, '.editorconfig'),
    'root = true\n[*]\nindent_style = tab\nend_of_line = crlf\n',
  );
  const script = `
    import {readFile} from 'node:fs/promises';
    import {compile} from ${JSON.stringify(pathToFileURL(join(repo, 'dist/index.js')).href)};
    const document=JSON.parse(await readFile('openapi.json','utf8'));
    console.log(JSON.stringify(await compile(document,{clients:['consumer','staff']})));
  `;
  const result = await exec(
    process.execPath,
    ['--input-type=module', '-e', script],
    { cwd: root },
  );
  assert.deepEqual(
    JSON.parse(result.stdout),
    await compile(document, { clients: ['consumer', 'staff'] }),
  );
});

test('formatter errors reject compilation with the generated filename', async (t) => {
  const broken = await brokenCompiler(t);
  await assert.rejects(
    broken.compile(fixture(), { clients: ['consumer', 'staff'] }),
    (error) =>
      error instanceof broken.ContractError &&
      /generated runtime\.ts: Oxfmt could not format TypeScript/.test(
        error.message,
      ),
  );
});

for (const existing of [false, true]) {
  test(`formatter errors preserve ${existing ? 'existing owned output bytes and mtimes' : 'a missing output directory'}`, async (t) => {
    const root = await temporary(t);
    const config = join(root, 'pom.json');
    const output = join(root, 'generated');
    await writeFile(
      config,
      JSON.stringify({
        version: 2,
        openapi: './openapi.json',
        output: './generated',
        clients: ['consumer', 'staff'],
      }),
    );
    await writeFile(join(root, 'openapi.json'), JSON.stringify(fixture()));
    if (existing) await runProject(config);
    const before = existing ? await fileSnapshot(output) : await readdir(root);
    const broken = await brokenCompiler(t);
    for (const check of [false, true]) {
      await assert.rejects(
        broken.runProject(config, { check }),
        /generated runtime\.ts: Oxfmt could not format TypeScript/,
      );
      assert.deepEqual(
        existing ? await fileSnapshot(output) : await readdir(root),
        before,
      );
    }
  });
}
