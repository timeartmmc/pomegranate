const banner = '// Generated by Pomegranate. Do not edit.\n';
const before = { 'a.ts': banner + 'old a', 'stale.ts': banner + 'old stale' };
const after = { 'a.ts': banner + 'new a', 'b.ts': banner + 'new b' };

function inject<K extends 'rm' | 'rename' | 'writeFile'>(
  t: TestContext,
  method: K,
  implementation: (typeof fs)[K],
) {
  t.mock.method(fs, method, implementation);
  syncBuiltinESMExports();
  return () => {
    t.mock.restoreAll();
    syncBuiltinESMExports();
  };
}

async function interrupt(
  t: TestContext,
  root: string,
  target: string,
  when: 'before' | 'after' = 'before',
  files: Record<string, string> = after,
) {
  let triggered = false;
  const publish = async (
    destination: unknown,
    original: () => Promise<void>,
  ) => {
    if (!triggered && destination === join(root, target)) {
      triggered = true;
      if (when === 'after') await original();
      throw new Error('injected publication interruption');
    }
    return original();
  };
  const remove = fs.rm;
  const rename = fs.rename;
  const restore =
    target === 'stale.ts'
      ? inject(t, 'rm', (path, options) =>
          publish(path, () => remove(path, options)),
        )
      : inject(t, 'rename', (from, to) => publish(to, () => rename(from, to)));
  try {
    await assert.rejects(
      synchronizeOutputs(root, files, [], false),
      /injected publication interruption/,
    );
  } finally {
    restore();
  }
  assert.equal(triggered, true);
}

for (const target of ['a.ts', 'b.ts', 'stale.ts', '.pom-manifest.json']) {
  for (const when of ['before', 'after'] as const) {
    void test(`generation resumes ${when} publishing ${target}`, async (t) => {
      const root = await temporary(t);
      await synchronizeOutputs(root, before, [], false);
      await fs.writeFile(join(root, 'notes.txt'), 'application-owned');
      await interrupt(t, root, target, when);
      const interrupted = await fileSnapshot(root);
      const checking = await synchronizeOutputs(root, after, [], true);
      assert.equal(
        checking.clean,
        target === '.pom-manifest.json' && when === 'after',
      );
      assert.deepEqual(await fileSnapshot(root), interrupted);
      await synchronizeOutputs(root, after, [], false);
      assert.equal(
        (await synchronizeOutputs(root, after, [], true)).clean,
        true,
      );
      assert.equal(
        await fs.readFile(join(root, 'a.ts'), 'utf8'),
        after['a.ts'],
      );
      assert.equal(
        await fs.readFile(join(root, 'b.ts'), 'utf8'),
        after['b.ts'],
      );
      assert.equal(
        await fs.readFile(join(root, 'notes.txt'), 'utf8'),
        'application-owned',
      );
      assert.deepEqual((await fs.readdir(root)).sort(), [
        '.pom-manifest.json',
        'a.ts',
        'b.ts',
        'notes.txt',
      ]);
    });
  }
}

void test('interrupted first generation and missing owned files can be regenerated', async (t) => {
  for (const initial of [false, true]) {
    const root = await temporary(t);
    if (initial) {
      await synchronizeOutputs(root, before, [], false);
      await fs.rm(join(root, 'a.ts'));
    }
    await interrupt(t, root, 'b.ts');
    await synchronizeOutputs(root, after, [], false);
    assert.equal((await synchronizeOutputs(root, after, [], true)).clean, true);
  }
});

void test('changed inputs replace current targets while preserving uncertain interrupted orphans', async (t) => {
  for (const initial of [false, true]) {
    const root = await temporary(t);
    if (initial) await synchronizeOutputs(root, before, [], false);
    await interrupt(t, root, '.pom-manifest.json');
    const orphan = banner + 'local edit to interrupted output';
    await fs.writeFile(join(root, 'b.ts'), orphan);
    const next = { 'a.ts': banner + 'third a', 'c.ts': banner + 'third c' };
    const result = await synchronizeOutputs(root, next, [], false);
    assert.ok(
      result.warnings.some(
        (warning) =>
          warning.code === 'preserved-stale-output' &&
          warning.path === join(root, 'b.ts'),
      ),
    );
    assert.equal(await fs.readFile(join(root, 'a.ts'), 'utf8'), next['a.ts']);
    assert.equal(await fs.readFile(join(root, 'c.ts'), 'utf8'), next['c.ts']);
    for (let retry = 0; retry < 2; retry++) {
      await synchronizeOutputs(root, next, [], false);
      assert.equal(await fs.readFile(join(root, 'b.ts'), 'utf8'), orphan);
    }
    const snapshot = await fileSnapshot(root);
    assert.equal((await synchronizeOutputs(root, next, [], true)).clean, false);
    assert.deepEqual(await fileSnapshot(root), snapshot);
    await fs.rm(join(root, 'b.ts'));
    assert.equal((await synchronizeOutputs(root, next, [], true)).clean, true);
  }
});

void test('new unowned targets and protected inputs are checked before retry writes', async (t) => {
  const root = await temporary(t);
  await synchronizeOutputs(root, before, [], false);
  await interrupt(t, root, 'stale.ts');
  await fs.writeFile(join(root, 'unowned.ts'), 'application-owned');
  const snapshot = await fileSnapshot(root);
  await assert.rejects(
    synchronizeOutputs(
      root,
      { ...after, 'unowned.ts': banner + 'generated' },
      [],
      false,
    ),
    /unowned output/,
  );
  for (const name of ['a.ts', 'stale.ts', '.pom-manifest.json'])
    await assert.rejects(
      synchronizeOutputs(root, after, [join(root, name)], false),
      /protected input/,
    );
  assert.deepEqual(await fileSnapshot(root), snapshot);
});

for (const phase of ['overwrite', 'remove'] as const) {
  void test(`an edit during publication is preserved before ${phase}`, async (t) => {
    const root = await temporary(t);
    await synchronizeOutputs(root, before, [], false);
    const manifest = await fs.readFile(join(root, '.pom-manifest.json'));
    const edited = phase === 'overwrite' ? 'b.ts' : 'stale.ts';
    const trigger = phase === 'overwrite' ? 'a.ts' : 'b.ts';
    const rename = fs.rename;
    let triggered = false;
    const restore = inject(t, 'rename', async (from, to) => {
      await rename(from, to);
      if (to === join(root, trigger)) {
        triggered = true;
        await fs.writeFile(join(root, edited), 'user edit');
      }
    });
    try {
      await assert.rejects(
        synchronizeOutputs(root, after, [], false),
        (error) => {
          assert.ok(error instanceof ContractError);
          assert.equal(error.location, edited);
          assert.match(error.message, new RegExp(`refusing to ${phase}`));
          return true;
        },
      );
    } finally {
      restore();
    }
    assert.equal(triggered, true);
    assert.equal(await fs.readFile(join(root, edited), 'utf8'), 'user edit');
    assert.deepEqual(
      await fs.readFile(join(root, '.pom-manifest.json')),
      manifest,
    );
    const interrupted = await fileSnapshot(root);
    assert.equal(
      (await synchronizeOutputs(root, after, [], true)).clean,
      false,
    );
    assert.deepEqual(await fileSnapshot(root), interrupted);
    if (phase === 'overwrite') {
      await assert.rejects(
        synchronizeOutputs(root, after, [], false),
        /unowned output/,
      );
      assert.deepEqual(await fileSnapshot(root), interrupted);
    } else {
      const retried = await synchronizeOutputs(root, after, [], false);
      assert.ok(
        retried.warnings.some(
          (warning) => warning.code === 'preserved-stale-output',
        ),
      );
      assert.equal(await fs.readFile(join(root, edited), 'utf8'), 'user edit');
    }
  });
}

void test('an edit after inspection blocks publication before replacing targets', async (t) => {
  const root = await temporary(t);
  await synchronizeOutputs(root, before, [], false);
  await interrupt(t, root, 'stale.ts');
  let edited: Awaited<ReturnType<typeof fileSnapshot>> | undefined;
  const write = fs.writeFile;
  const restore = inject(t, 'writeFile', async (path, ...args) => {
    await write(path, ...args);
    if (
      typeof path === 'string' &&
      path.includes('.pom-stage-') &&
      path.endsWith('.pom-manifest.json')
    ) {
      await write(join(root, 'a.ts'), 'user edit after inspection');
      edited = await fileSnapshot(root);
    }
  });
  try {
    await assert.rejects(
      synchronizeOutputs(root, after, [], false),
      /output changed during generation/,
    );
  } finally {
    restore();
  }
  assert.deepEqual(await fileSnapshot(root), present(edited));
});

