void test('nullable type arrays preserve equivalent generated bytes and do not mutate input', async () => {
  const source = schemaFixture();
  const equivalent = structuredClone(source);
  for (const { name, equivalent: schema } of nullableTypeCases)
    Object.assign(equivalent.components.schemas, {
      [name]: structuredClone(schema),
    });
  const options: CompileOptions = {
    clients: ['samples'],
    standalone: {
      nullable_input: {
        schema: '#/components/schemas/TypeArrayReferences',
        usage: 'request',
      },
      nullable_output: {
        schema: '#/components/schemas/TypeArrayEnum',
        usage: 'response',
      },
    },
  };
  const expected = await compile(equivalent, options);
  const before = structuredClone(source);
  assert.deepEqual(await compile(source, options), expected);
  assert.deepEqual(source, before);
  // Reversing the type order changes neither its meaning nor the canonical output.
  for (const schema of Object.values(source.components.schemas))
    if ('type' in schema && Array.isArray(schema.type)) schema.type.reverse();
  assert.deepEqual(await compile(source, options), expected);
});

void test('nullable formats and input defaults preserve their existing equivalents', async () => {
  for (const schema of [
    { type: 'string', format: 'date' },
    { type: 'string', format: 'date-time' },
    { type: 'string', format: 'uuid' },
    { type: 'string', minLength: 1 },
  ]) {
    const document = fixture();
    Object.assign(
      preparation(document).requestBody.content['application/json'],
      {
        schema: {
          ...nullable(schema),
          default: null,
        },
      },
    );
    const expected = await compile(document, selection);
    Object.assign(
      preparation(document).requestBody.content['application/json'],
      {
        schema: {
          ...schema,
          type: [schema.type, 'null'],
          default: null,
        },
      },
    );
    assert.deepEqual(await compile(document, selection), expected);
  }
});

