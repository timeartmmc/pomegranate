void test('nullable syntax observes the same inline nesting limit as explicit unions', async () => {
  for (const depth of [15, 16]) {
    let schema: Schema = { type: ['string', 'null'] };
    let equivalent = nullable({ type: 'string' });
    for (let index = 0; index < depth; index++) {
      schema = { type: ['array', 'null'], items: schema };
      equivalent = nullable({ type: 'array', items: equivalent });
    }
    const document = fixture();
    Object.assign(document.components.schemas, { Deep: schema });
    const options: CompileOptions = {
      clients: [],
      standalone: {
        deep: { schema: '#/components/schemas/Deep', usage: 'response' },
      },
    };
    if (depth === 15) {
      const expected = await compile(document, options);
      Object.assign(document.components.schemas, { Deep: equivalent });
      assert.deepEqual(await compile(document, options), expected);
    } else {
      await assert.rejects(
        compile(document, options),
        /inline schema nesting exceeds/,
      );
      Object.assign(document.components.schemas, { Deep: equivalent });
      await assert.rejects(
        compile(document, options),
        /inline schema nesting exceeds/,
      );
    }
  }
});

void test('nullable defaults, requiredness, transport omission and response stripping remain intact', async (t) => {
  const document = fixture();
  Object.assign(document.components.schemas, {
    PreparationInput: {
      type: ['object', 'null'],
      properties: {
        required: {
          type: ['string', 'null'],
          minLength: 1,
          default: 'annotation',
        },
        optional: { type: ['integer', 'null'], minimum: 0, default: 1 },
      },
      required: ['required'],
    },
  });
  Object.assign(preparation(document), {
    parameters: [
      preparation(document).parameters[0],
      {
        name: 'q',
        in: 'query',
        schema: { type: ['integer', 'null'], minimum: 0 },
      },
      {
        name: 'X-Note',
        in: 'header',
        schema: { type: ['string', 'null'], minLength: 1 },
      },
      {
        name: 'X-State',
        in: 'header',
        required: true,
        schema: { type: ['string', 'null'], enum: ['ready'] },
      },
    ],
  });
  const root = await temporary(t);
  await symlink(
    fileURLToPath(new URL('../node_modules', import.meta.url)),
    join(root, 'node_modules'),
    process.platform === 'win32' ? 'junction' : 'dir',
  );
  const options: CompileOptions = {
    ...selection,
    standalone: {
      response: { schema: '#/components/schemas/Pending', usage: 'response' },
    },
  };
  Object.assign(document.components.schemas.Pending, {
    type: ['object', 'null'],
  });
  await writeFile(join(root, 'package.json'), '{"type":"module"}');
  for (const [name, source] of Object.entries(await compile(document, options)))
    await writeFile(join(root, name), source);
  const { operations, RequestValidationError } = (await import(
    pathToFileURL(join(root, 'client.consumer.ts')).href
  )) as RuntimeClient;
  const build = (body: unknown, extra: Record<string, unknown> = {}) =>
    entry(operations, 'prepareWidget').build({
      path: { widgetId: 'id' },
      headers: { 'X-State': 'ready' },
      body,
      ...extra,
    });
  assert.equal(build(null).body, null);
  assert.deepEqual(build({ required: null }).body, { required: null });
  for (const body of [
    {},
    { required: undefined },
    { required: '' },
    { required: null, optional: -1 },
    { required: null, extra: true },
  ])
    assert.throws(() => build(body), RequestValidationError);
  assert.deepEqual(build({ required: 'value', optional: undefined }).body, {
    required: 'value',
    optional: undefined,
  });
  const omitted = build(null, {
    query: { q: null },
    headers: { 'X-Note': null, 'X-State': 'ready' },
  });
  assert.equal(omitted.url.includes('?'), false);
  assert.equal(Object.hasOwn(omitted.headers, 'x-note'), false);
  assert.ok(build(null, { query: { q: 0 } }).url.endsWith('?q=0'));
  assert.throws(
    () => build(null, { query: { q: -1 } }),
    RequestValidationError,
  );
  assert.throws(
    () => build(null, { headers: { 'X-State': null } }),
    RequestValidationError,
  );
  const { schema } = (await import(
    pathToFileURL(join(root, 'standalone.response.ts')).href
  )) as StandaloneModule;
  assert.equal(schema.parse(null), null);
  assert.deepEqual(
    schema.parse({ state: 'pending', reference: 'synthetic', extra: true }),
    { state: 'pending', reference: 'synthetic' },
  );
  assert.equal(schema.safeParse({ state: 'pending' }).success, false);
});

void test('invalid nullable syntax cannot modify an existing output set', async (t) => {
  const root = await temporary(t);
  const config = join(root, 'pom.json');
  const input = join(root, 'openapi.json');
  await writeFile(
    config,
    JSON.stringify({
      version: 2,
      openapi: './openapi.json',
      output: './generated',
      ...selection,
    }),
  );
  await writeFile(input, JSON.stringify(fixture()));
  await runProject(config);
  const before = await fileSnapshot(join(root, 'generated'));
  const document = fixture();
  Object.assign(document.components.schemas, {
    Bad: { type: ['string', 'integer', 'null'] },
  });
  await writeFile(input, JSON.stringify(document));
  for (const check of [false, true]) {
    await assert.rejects(runProject(config, { check }), /type arrays require/);
    assert.deepEqual(await fileSnapshot(join(root, 'generated')), before);
  }
});
