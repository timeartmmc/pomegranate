import assert from 'node:assert/strict';
import test from 'node:test';
import { compile, ContractError } from '../dist/index.js';
import { buildDescriptor } from '../dist/descriptor.js';
import { fixture } from './helpers.ts';

const selection = { clients: ['consumer', 'staff'] };

void test('OpenAPI 3.1 patch versions preserve generated bytes and input documents', async () => {
  const expected = await compile(fixture(), selection);
  for (const version of ['3.1.0', '3.1.1', '3.1.2', '3.1.12', '3.1.100']) {
    const document = fixture();
    document.openapi = version;
    const before = structuredClone(document);
    assert.deepEqual(await compile(document, selection), expected, version);
    assert.deepEqual(document, before, version);
  }
});

void test('unsupported and malformed OpenAPI versions fail at the version field', async () => {
  for (const version of [
    undefined,
    null,
    true,
    3.1,
    ['3.1.0'],
    {},
    '',
    '3.1',
    '3.1.01',
    '3.1.-1',
    '3.1.0.0',
    '3.1.0-rc.1',
    '3.1.0+build',
    'v3.1.0',
    ' 3.1.0',
    '3.1.0 ',
    '3.1.0\n',
    '3.1.0\r\n',
    '3.0',
    '3.0.01',
    '3.0.-1',
    '3.0.0-rc.1',
    '3.0.0+build',
    '3.0.0\n',
    '3.2.0',
    '4.0.0',
  ]) {
    for (const extension of ['none', 'root', 'nested', 'semantic']) {
      const document = fixture();
      Object.assign(document, { openapi: version });
      if (extension === 'root') Object.assign(document, { 'x-note': true });
      if (extension === 'nested')
        Object.assign(document.components.schemas.Widget, { 'x-note': true });
      if (extension === 'semantic')
        Object.assign(document.components.schemas.Widget, {
          'x-multi-segment': true,
        });
      const versionError = (error: unknown) =>
        error instanceof ContractError &&
        error.location === 'openapi' &&
        /expected an OpenAPI 3\.0\.x or 3\.1\.x version/.test(error.message);
      const label = `${JSON.stringify(version)} with ${extension} extension`;
      await assert.rejects(compile(document, selection), versionError, label);
      assert.throws(() => buildDescriptor(document), versionError, label);
    }
  }
});

void test('accepting a patch version preserves schema and operation-policy diagnostics', async () => {
  const unsupportedSchema = fixture();
  unsupportedSchema.openapi = '3.1.2';
  Object.assign(unsupportedSchema.components.schemas.Widget.properties, {
    id: {
      type: 'string',
      format: 'idn-email',
    },
  });
  await assert.rejects(
    compile(unsupportedSchema, selection),
    /unsupported format/,
  );

  const invalidPolicy = fixture();
  invalidPolicy.openapi = '3.1.1';
  invalidPolicy['x-pom-policy'].version = 1;
  await assert.rejects(
    compile(invalidPolicy, selection),
    /expected policy version 3/,
  );
});
