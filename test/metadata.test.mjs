test('metadata-only updates leave owned files untouched; invalid metadata never writes', async (t) => {
  const root = await temporary(t);
  const config = join(root, 'pom.json');
  const input = join(root, 'openapi.json');
  const output = join(root, 'generated');
  await writeFile(
    config,
    JSON.stringify({
      version: 2,
      openapi: './openapi.json',
      output: './generated',
      ...selection,
    }),
  );
  await writeFile(input, JSON.stringify(fixture()));
  await runProject(config);
  await writeFile(join(output, 'notes.txt'), 'unrelated content');
  const before = await fileSnapshot(output);
  await writeFile(input, JSON.stringify(annotateDocument(fixture())));
  assert.equal((await runProject(config, { check: true })).clean, true);
  assert.equal((await runProject(config)).clean, true);
  assert.deepEqual(await fileSnapshot(output), before);
  const invalidDocument = annotateDocument(fixture());
  invalidDocument.info.license.name = 1;
  await writeFile(input, JSON.stringify(invalidDocument));
  for (const check of [false, true]) {
    await assert.rejects(runProject(config, { check }), /info.license.name/);
    assert.deepEqual(await fileSnapshot(output), before);
  }
  const missingRoot = join(root, 'missing-case');
  await mkdir(missingRoot);
  const missingConfig = join(missingRoot, 'pom.json');
  await writeFile(
    missingConfig,
    JSON.stringify({
      version: 2,
      openapi: '../openapi.json',
      output: './generated',
      ...selection,
    }),
  );
  for (const check of [false, true]) {
    await assert.rejects(
      runProject(missingConfig, { check }),
      /info.license.name/,
    );
    await assert.rejects(stat(join(missingRoot, 'generated')), {
      code: 'ENOENT',
    });
    assert.deepEqual(await readdir(missingRoot), ['pom.json']);
  }
});
