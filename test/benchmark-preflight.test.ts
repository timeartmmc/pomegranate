const exec = promisify(execFile);

void test('benchmark preflight runs generated code without checkout dependencies and reports no performance verdict', async () => {
  const { stdout } = await exec(process.execPath, [
    fileURLToPath(new URL('../bench/preflight.ts', import.meta.url)),
  ]);
  const result = record(json(stdout));
  assert.equal(result.schemaVersion, 1);
  assert.deepEqual(result.case, { id: 'json-response', version: 2 });
  assert.match(String(result.caseSha256), /^[a-f0-9]{64}$/);
  assert.equal(result.behavior, 'verified');
  assert.equal(result.performance, 'unmeasured');
  assert.equal(result.node, process.version);
  const files = result.generated;
  assert.ok(Array.isArray(files) && files.length > 0);
  for (const value of files) {
    const file = record(value);
    assert.equal(typeof file.name, 'string');
    assert.ok(typeof file.bytes === 'number' && file.bytes > 0);
    assert.match(String(file.sha256), /^[a-f0-9]{64}$/);
  }
});

void test('preflight retains qualified generated bytes and preserves an existing destination', async (t) => {
  const root = await temporary(t);
  const output = join(root, 'generated');
  const command = fileURLToPath(
    new URL('../bench/preflight.ts', import.meta.url),
  );
  const { stdout } = await exec(process.execPath, [command, output]);
  const files = record(json(stdout)).generated;
  assert.ok(Array.isArray(files));
  assert.equal((await readdir(output)).length, files.length + 1);
  for (const value of files) {
    const file = record(value);
    assert.ok(typeof file.name === 'string');
    const bytes = await readFile(join(output, file.name));
    assert.equal(bytes.length, file.bytes);
    assert.equal(createHash('sha256').update(bytes).digest('hex'), file.sha256);
  }
  verifyJsonResponse(
    jsonResponseSubject(
      await importGenerated<unknown>(output, 'client.consumer.ts'),
      await importGenerated<unknown>(output, 'client.consumer.schemas.ts'),
    ),
  );
  await writeFile(join(output, 'keep.txt'), 'caller-owned');
  await assert.rejects(exec(process.execPath, [command, output]), /EEXIST/);
  assert.equal(
    await readFile(join(output, 'keep.txt'), 'utf8'),
    'caller-owned',
  );
});

void test('benchmark oracle accepts real generated behavior and rejects faster shortcuts', async (t) => {
  const { document, options } = jsonResponseWorkload();
  const root = await generatedTestWorkspace(
    t,
    await compile(document, options),
  );
  const client = await importGenerated<unknown>(root, 'client.consumer.ts');
  const schemas = await importGenerated<unknown>(
    root,
    'client.consumer.schemas.ts',
  );
  const subject = jsonResponseSubject(client, schemas);
  verifyJsonResponse(subject);

  const corruptSuccess = (
    alter: (result: Record<string, unknown>, input: unknown) => void,
  ): JsonResponseSubject => ({
    ...subject,
    validate(input) {
      const result = record(subject.validate(input));
      if (result.success === true) alter(result, input);
      return result;
    },
  });

  await t.test('returning caller data', () => {
    assert.throws(
      () =>
        verifyJsonResponse(
          corruptSuccess((result, input) => {
            result.data = input;
          }),
        ),
      assert.AssertionError,
    );
  });

  await t.test(
    'retaining a nested container with otherwise correct values',
    () => {
      const mutant = corruptSuccess((result, input) => {
        const sourceItems = record(input).items;
        const outputItems = record(result.data).items;
        assert.ok(Array.isArray(sourceItems) && Array.isArray(outputItems));
        if (sourceItems.length > 0)
          record(outputItems[0]).details = record(sourceItems[0]).details;
      });
      assert.throws(
        () => verifyJsonResponse(mutant),
        /output must detach every container/,
      );
    },
  );

  await t.test(
    'mutating the caller input while producing correct output',
    () => {
      const mutant = corruptSuccess((_result, input) => {
        record(input).mutation = true;
      });
      assert.throws(
        () => verifyJsonResponse(mutant),
        /validation must preserve its input/,
      );
    },
  );

  for (const method of ['validate', 'parseResponse'] as const)
    await t.test(`caching mutable results from ${method}`, () => {
      const cache = new WeakMap<object, unknown>();
      const mutant: JsonResponseSubject = {
        ...subject,
        [method](input: unknown) {
          const key = record(input);
          if (!cache.has(key)) cache.set(key, subject[method](input));
          return cache.get(key);
        },
      };
      assert.throws(
        () => verifyJsonResponse(mutant),
        /calls must return independent containers/,
      );
    });

  await t.test('returning fresh copies of a stale cached snapshot', () => {
    const cache = new WeakMap<object, Record<string, unknown>>();
    const mutant: JsonResponseSubject = {
      ...subject,
      validate(input) {
        const key = record(input);
        const result = cache.get(key) ?? record(subject.validate(input));
        cache.set(key, result);
        return result.success === true
          ? { ...result, data: structuredClone(result.data) }
          : result;
      },
    };
    assert.throws(() => verifyJsonResponse(mutant), assert.AssertionError);
  });

  for (const target of ['root', 'items', 'record', 'details'] as const)
    await t.test(`freezing the response ${target}`, () => {
      const mutant = corruptSuccess((result) => {
        const data = record(result.data);
        const items = data.items;
        assert.ok(Array.isArray(items));
        if (target === 'root') Object.freeze(data);
        if (target === 'items') Object.freeze(items);
        if (items.length > 0) {
          const first = record(items[0]);
          if (target === 'record') Object.freeze(first);
          if (target === 'details') Object.freeze(record(first.details));
        }
      });
      assert.throws(() => verifyJsonResponse(mutant), TypeError);
    });

  await t.test('freezing a protocol success body', () => {
    const mutant: JsonResponseSubject = {
      ...subject,
      parseResponse(input) {
        const result = record(subject.parseResponse(input));
        if (result.kind === 'success') Object.freeze(record(result.data));
        return result;
      },
    };
    assert.throws(() => verifyJsonResponse(mutant), TypeError);
  });

  await t.test('skipping constraints on invalid values', () => {
    const mutant: JsonResponseSubject = {
      ...subject,
      validate(input) {
        const result = record(subject.validate(input));
        return result.success === true ? result : { success: true, data: {} };
      },
    };
    assert.throws(() => verifyJsonResponse(mutant), assert.AssertionError);
  });

  await t.test('reading a field excluded from the response', () => {
    const mutant: JsonResponseSubject = {
      ...subject,
      validate(input) {
        const items = record(input).items;
        if (Array.isArray(items))
          for (const item of items) void record(item).secret;
        return subject.validate(input);
      },
    };
    assert.throws(
      () => verifyJsonResponse(mutant),
      /excluded response field was read/,
    );
  });

  await t.test('accepting invalid protocol responses', () => {
    const mutant: JsonResponseSubject = {
      ...subject,
      parseResponse(input) {
        const result = record(subject.parseResponse(input));
        return { ...result, kind: 'success' };
      },
    };
    assert.throws(() => verifyJsonResponse(mutant), assert.AssertionError);
  });

  await t.test('building the wrong operation', () => {
    assert.throws(
      () =>
        verifyJsonResponse({
          ...subject,
          build: () => ({ method: 'GET', url: '/wrong' }),
        }),
      assert.AssertionError,
    );
  });

  await t.test('dropping the operation from its inventory', () => {
    assert.throws(
      () => jsonResponseSubject({ operations: {} }, schemas),
      assert.AssertionError,
    );
  });

  await t.test('throwing instead of returning a failure for null', () => {
    const mutant: JsonResponseSubject = {
      ...subject,
      validate(input) {
        if (input === null) throw new TypeError('synthetic null shortcut');
        return subject.validate(input);
      },
    };
    assert.throws(() => verifyJsonResponse(mutant), /synthetic null shortcut/);
  });

  await t.test('discarding diagnostic paths', () => {
    const mutant: JsonResponseSubject = {
      ...subject,
      validate(input) {
        const result = record(subject.validate(input));
        if (result.success === true) return result;
        return {
          success: false,
          error: Object.assign(new Error('invalid'), {
            issues: [{ path: [], message: 'invalid' }],
          }),
        };
      },
    };
    assert.throws(
      () => verifyJsonResponse(mutant),
      /expected issue path and part/,
    );
  });

  await t.test('discarding protocol evidence', () => {
    const mutant: JsonResponseSubject = {
      ...subject,
      parseResponse(input) {
        const result = record(subject.parseResponse(input));
        return result.kind === 'protocol' ? { kind: 'protocol' } : result;
      },
    };
    assert.throws(() => verifyJsonResponse(mutant), assert.AssertionError);
  });

  await t.test('rejecting a parameterized JSON content type', () => {
    const mutant: JsonResponseSubject = {
      ...subject,
      parseResponse(input) {
        const headers = record(record(input).headers);
        return headers['content-type'] === 'application/json; charset=utf-8'
          ? { kind: 'protocol' }
          : subject.parseResponse(input);
      },
    };
    assert.throws(() => verifyJsonResponse(mutant), assert.AssertionError);
  });

  await t.test('requiring an excluded response field', () => {
    const mutant: JsonResponseSubject = {
      ...subject,
      validate(input) {
        const result = record(subject.validate(input));
        const items = input === null ? undefined : record(input).items;
        return result.success === true &&
          Array.isArray(items) &&
          items.some((item) => !Object.hasOwn(record(item), 'secret'))
          ? { success: false }
          : result;
      },
    };
    assert.throws(() => verifyJsonResponse(mutant), assert.AssertionError);
  });

  await t.test('rejecting a valid upper boundary', () => {
    const mutant: JsonResponseSubject = {
      ...subject,
      validate(input) {
        const result = record(subject.validate(input));
        const items = input === null ? undefined : record(input).items;
        return result.success === true &&
          Array.isArray(items) &&
          items.some((item) => record(item).label === 'x'.repeat(32))
          ? { success: false }
          : result;
      },
    };
    assert.throws(() => verifyJsonResponse(mutant), assert.AssertionError);
  });
});
