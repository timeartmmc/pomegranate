void test('metadata preserves every generated byte, operation, schema and input document', async (t) => {
  const fetch = t.mock.method(globalThis, 'fetch', () => {
    throw new Error('annotations must not fetch');
  });
  for (const [document, options] of [
    [fixture(), selection],
    [multipartFixture(), multipartSelection],
    [
      schemaFixture(),
      { clients: ['samples'], standalone: standaloneSelection },
    ],
  ] satisfies [unknown, CompileOptions][]) {
    const expected = await compile(document, options);
    const annotated = annotateDocument(structuredClone(document));
    const before = structuredClone(annotated);
    assert.deepEqual(await compile(annotated, options), expected);
    assert.deepEqual(annotated, before);
  }
  assert.equal(fetch.mock.callCount(), 0);
});

