const banner = '// Generated by Pomegranate. Do not edit.\n';
// Namespace access lets bundlers select Zod exports instead of retaining the
// named `z` object's complete validator namespace (also used by copied helpers).
const zodImport = "import * as z from 'zod';";
type Entries = [string | number, Expression][];

function operationScope(id: string): string {
  // IDs contain ASCII letters, digits and underscores. Escape every underscore
  // so an ID cannot absorb a role suffix: read_options headers must not collide
  // with read's options headers. Escaping the escape marker also distinguishes
  // read_uoptions. Names depend only on this operation, not generation order.
  return `operation_${id.replaceAll('_', '_u')}`;
}

// Source consumers resolve real TypeScript files; JavaScript emission rewrites
// their extensions instead of requiring bundler-specific resolver aliases.
function helperImports(helpers: ReadonlySet<string>): string {
  const shared = [...helpers].filter((name) => name !== 'browserFile').sort();
  return [
    shared.length ? `import {${shared.join(',')}} from './runtime.ts';` : '',
    helpers.has('browserFile')
      ? "import {browserFile} from './runtime.browser.ts';"
      : '',
  ].join('\n');
}

function zodTypeImports(imports: ReadonlySet<string>): string {
  return imports.size
    ? `import type { ${[...imports].sort().join(', ')} } from 'zod';`
    : '';
}

function renderComponents(
  descriptor: Descriptor,
  selections: readonly { direction: Direction; names: readonly string[] }[],
  target?: Client['target'],
  exportValidators = false,
) {
  const renderer = schemaRenderer(
    descriptor.schemas,
    (name, direction) => identifier(schemaSymbol(name, direction)),
    typeSymbol,
    target,
  );
  const declarations = selections.flatMap(({ direction, names }) =>
    names.map((name) => {
      const schema = descriptor.schemas[name]!;
      const symbol = schemaSymbol(name, direction);
      const type = typeSymbol(name, direction);
      const expression = renderer.schema(
        schema,
        direction,
        `components.schemas.${name}`,
        symbol,
      );
      return `type ${type} = ${schemaType(schema, direction, target)};
      ${renderer.takeDeclarations()}
      ${exportValidators ? 'export ' : ''}const ${symbol}: ${validatorType(schema, type, descriptor.schemas, renderer.typeImports)} = ${pureInitializer(expression, `components.schemas.${name}`)};`;
    }),
  );
  return { renderer, declarations: declarations.join('\n') };
}

function parameterOptions(
  operation: Operation,
  parameters: Operation['parameters'],
  renderer: SchemaRenderer,
  headers?: ReadonlyMap<string, Expression>,
) {
  const entries: Entries = [];
  let required = operation.body.kind !== 'none';
  for (const [position, field] of [
    ['path', 'path'],
    ['query', 'query'],
    ['header', 'headers'],
  ] as const) {
    const group = parameters.filter((parameter) => parameter.in === position);
    if (group.length === 0) continue;
    const requiredGroup = group.some((parameter) => parameter.required);
    required ||= requiredGroup;
    const fields: Entries = group.map((parameter, index) => {
      const schema =
        (position === 'header' ? headers?.get(parameter.name) : undefined) ??
        renderer.schema(
          parameter.schema,
          'request',
          `${operation.id}.parameters.${parameter.name}`,
          `${operationScope(operation.id)}_options_${position}_${index}`,
          true,
        );
      return [
        parameter.name,
        parameter.required ? schema : method(schema, 'optional'),
      ];
    });
    const schema = method(
      method(identifier('z'), 'object', [object(fields)]),
      'strict',
    );
    entries.push([field, requiredGroup ? schema : method(schema, 'optional')]);
  }
  if (operation.body.kind !== 'none')
    entries.push([
      'body',
      renderer.schema(
        operation.body.schema,
        'request',
        `${operation.id}.requestBody`,
        `${operationScope(operation.id)}_body`,
        true,
      ),
    ]);
  if (entries.length === 0) renderer.helpers.add('recordSchema');
  const options =
    entries.length === 0
      ? call(identifier('recordSchema'), [method(identifier('z'), 'never')])
      : method(method(identifier('z'), 'object', [object(entries)]), 'strict');
  return required ? options : method(options, 'optional');
}

function requestHeaders(operation: Operation, renderer: SchemaRenderer) {
  const schemas = new Map<string, Expression>();
  const specs = object(
    operation.parameters
      .filter((parameter) => parameter.in === 'header')
      .map((header, index): Entries[number] => {
        const scope = `${operationScope(operation.id)}_header_${index}`;
        const location = `${operation.id}.headers.${header.name}`;
        // Both validation stages use one rule. Bind it before the option
        // declarations, after any nullable/reference dependencies it needs.
        const schema = renderer.bind(
          scope,
          renderer.schema(header.schema, 'request', location, scope, true),
          location,
        );
        schemas.set(header.name, schema);
        return [
          header.name.toLowerCase(),
          object([
            ['required', literal(header.required)],
            ['schema', schema],
          ]),
        ];
      }),
  );
  return { schemas, specs };
}

function responseSpecs(
  operation: Operation,
  renderer: SchemaRenderer,
): Expression {
  return object(
    operation.responses.map((response) => {
      const prefix = `${operationScope(operation.id)}_response_${response.status}`;
      const headers = object(
        response.headers.map((header, index) => [
          header.name,
          object([
            ['required', literal(header.required)],
            [
              'schema',
              renderer.schema(
                header.schema,
                'response',
                `${operation.id}.responses.${response.status}.headers.${header.name}`,
                `${prefix}_header_${index}`,
                true,
              ),
            ],
          ]),
        ]),
      );
      const entries: Entries = [
        ['bodyKind', literal(response.body.kind)],
        ['headers', headers],
      ];
      if (response.body.kind === 'json')
        entries.push([
          'schema',
          renderer.schema(
            response.body.schema,
            'response',
            `${operation.id}.responses.${response.status}.body`,
            prefix,
            true,
          ),
        ]);
      return [response.status, object(entries)];
    }),
  );
}

function operationExpression(
  operation: Operation,
  client: Client,
  renderer: SchemaRenderer,
): Expression {
  const headers = requestHeaders(operation, renderer);
  const parameters = operation.parameters.filter(
    (parameter) =>
      parameter.in !== 'header' ||
      !client.transportHeaders.includes(parameter.name.toLowerCase()),
  );
  const entries: Entries = [
    ['operationId', literal(operation.id)],
    ['method', literal(operation.method)],
    ['path', literal(operation.path)],
    ['policy', data(operation.policy)],
    ['bodyKind', literal(operation.body.kind)],
    [
      'parameters',
      data(
        parameters.map(({ name, in: position, required }) => ({
          name,
          in: position,
          required,
        })),
      ),
    ],
    [
      'options',
      parameterOptions(operation, parameters, renderer, headers.schemas),
    ],
    ['headers', headers.specs],
    ['responses', responseSpecs(operation, renderer)],
  ];
  if (operation.body.kind === 'multipart')
    entries.push(['multipart', data(operation.body.fields)]);
  return call(identifier('defineOperation'), [object(entries)]);
}

function renderClient(
  descriptor: Descriptor,
  client: Client,
): Readonly<Record<string, string>> {
  const selections = [
    { direction: 'request', names: client.requestSchemas },
    { direction: 'response', names: client.responseSchemas },
  ] as const;
  const { renderer: components, declarations } = renderComponents(
    descriptor,
    selections,
    client.target,
    true,
  );
  const schemaMaps = selections.map(({ direction, names }) => {
    const expression = method(identifier('Object'), 'freeze', [
      object(
        names.map((name) => [name, identifier(schemaSymbol(name, direction))]),
      ),
    ]);
    const fields = names
      .map((name) => `${propertyKey(name)}: ${typeSymbol(name, direction)};`)
      .join('\n');
    return `export const ${direction}Schemas = ${pureInitializer(expression, `client.${client.name}.${direction}Schemas`)};
      export type ${direction === 'request' ? 'Request' : 'Response'}Types = {${fields}};`;
  });
  const emittedSchema = `${banner}
    ${components.usesZod() ? zodImport : ''}
    ${zodTypeImports(components.typeImports)}
    ${helperImports(components.helpers)}
    ${declarations}
    ${schemaMaps.join('\n')}`;
  const schemaImports = new Set<string>();
  let usesSchemaTypes = false;
  const inline = schemaRenderer(
    descriptor.schemas,
    (name, direction) => {
      const symbol = schemaSymbol(name, direction);
      schemaImports.add(symbol);
      return identifier(symbol);
    },
    (name, direction) => {
      usesSchemaTypes = true;
      return `schemas.${direction === 'request' ? 'Request' : 'Response'}Types[${JSON.stringify(name)}]`;
    },
    client.target,
  );
  inline.helpers.add('defineOperation');
  // Internal named exports share the same instances as the public aggregates.
  // Query modules can retain selected operations without importing the registry.
  const operationDeclarations = client.operations.map(
    (operation) =>
      `export const ${operationScope(operation.id)} = ${pureInitializer(operationExpression(operation, client, inline), `client.${client.name}.${operation.id}`)};`,
  );
  const operations = method(identifier('Object'), 'freeze', [
    object(
      client.operations.map((operation) => [
        operation.id,
        identifier(operationScope(operation.id)),
      ]),
    ),
  ]);
  const emittedOperations = `${banner}${zodImport}
    ${zodTypeImports(inline.typeImports)}
    ${helperImports(inline.helpers)}
    ${schemaImports.size ? `import { ${[...schemaImports].sort().join(', ')} } from './client.${client.name}.schemas.ts';` : ''}
    ${usesSchemaTypes ? `import type * as schemas from './client.${client.name}.schemas.ts';` : ''}
    ${inline.takeDeclarations()}
    ${operationDeclarations.join('\n')}
    export const operations = ${pureInitializer(operations, `client.${client.name}.operations`)};`;
  const index = `${banner}
    export { operations } from './client.${client.name}.operations.ts';
    export type { RequestTypes, ResponseTypes } from './client.${client.name}.schemas.ts';
    export { RequestValidationError } from './runtime.ts';
    export type { PreparedRequest, Responses, ProtocolResult, ProtocolFailure, ObservedResponse, HeaderContext, MultipartField } from './runtime.ts';
    ${
      client.execution
        ? `export { createClient, ResponseError } from './client.${client.name}.execute.ts';
    export type { ClientConfig, Executor, Execution, ExecutionContext, ResponseInspection, ValidatedResponse, CancellationEvent, CancellationMapper, TypedResponseError } from './client.${client.name}.execute.ts';`
        : ''
    }`;
  return {
    [`client.${client.name}.schemas.ts`]: emittedSchema,
    [`client.${client.name}.operations.ts`]: emittedOperations,
    [`client.${client.name}.ts`]: index,
    ...(client.execution
      ? { [`client.${client.name}.execute.ts`]: renderExecution(client) }
      : {}),
    ...(client.queries.length + client.infiniteQueries.length > 0
      ? {
          [`client.${client.name}.queries.ts`]: renderQueries(
            descriptor,
            client,
          ),
        }
      : {}),
  };
}

function renderExecution(client: Client): string {
  const entries = client.operations.map(
    (operation) =>
      `${propertyKey(operation.id)}: defineCall({ operation: operations.${operation.id}, ...runtime, client: ${JSON.stringify(client.name)}, operationId: ${JSON.stringify(operation.id)} })`,
  );
  return `${banner}
    import { operations } from './client.${client.name}.operations.ts';
    import { defineCall } from './call-runtime.ts';
    import { executionConfig } from './execution-runtime.ts';
    import type { ClientConfig } from './execution-runtime.ts';
    import type { ExecutionClient } from './call-runtime.ts';
    export { ResponseError } from './execution-runtime.ts';
    export type { ClientConfig, Executor, Execution, ExecutionContext, ResponseInspection, ValidatedResponse, CancellationEvent, CancellationMapper, TypedResponseError } from './execution-runtime.ts';
    export function createClient(config: ClientConfig): ExecutionClient<typeof operations> {
      const runtime = executionConfig(config);
      return Object.freeze({ ${entries.join(',')} });
    }`;
}

function renderQueries(descriptor: Descriptor, client: Client): string {
  const selectedTypes = client.queries
    .map(
      (operation) =>
        `${propertyKey(operation.id)}: typeof ${operationScope(operation.id)};`,
    )
    .join('\n');
  const entries = client.queries.map(
    (operation) =>
      `${propertyKey(operation.id)}: defineQuery({ operation: ${operationScope(operation.id)}, bodyCache: ${operation.responses.filter((response) => response.status >= 200 && response.status < 300).every((response) => response.body.kind !== 'none')}, ...runtime, client: ${JSON.stringify(client.name)}, operationId: ${JSON.stringify(operation.id)} })`,
  );
  // Removing cursors and transport headers can remove every schema reference
  // from base inputs, even when the ordinary client needs those components.
  const schemaImports = new Set<string>();
  let usesSchemaTypes = false;
  const renderer = schemaRenderer(
    descriptor.schemas,
    (name, direction) => {
      const symbol = schemaSymbol(name, direction);
      schemaImports.add(symbol);
      return identifier(symbol);
    },
    (name, direction) => {
      usesSchemaTypes = true;
      return `schemas.${direction === 'request' ? 'Request' : 'Response'}Types[${JSON.stringify(name)}]`;
    },
    client.target,
  );
  const inputs: string[] = [];
  const infiniteTypes: string[] = [];
  const infiniteEntries = client.infiniteQueries.map(
    ({ operation, binding }) => {
      const offset = 'offset' in binding;
      const name = `infinite_${operationScope(operation.id)}_input`;
      const parameters = operation.parameters.filter(
        (parameter) =>
          !(
            parameter.in === 'query' &&
            parameter.name === (offset ? binding.offset : binding.cursor)
          ) &&
          !(
            parameter.in === 'header' &&
            client.transportHeaders.includes(parameter.name.toLowerCase())
          ),
      );
      inputs.push(
        `const ${name} = ${pureInitializer(parameterOptions(operation, parameters, renderer), `infiniteQueries.${client.name}.${operation.id}`)};`,
      );
      const op = operationScope(operation.id);
      infiniteTypes.push(
        `${propertyKey(operation.id)}: InfiniteQueryFactoryFor<typeof ${op}, z.input<typeof ${name}>, ${JSON.stringify(binding.items)}${offset ? ', number' : ''}>;`,
      );
      if (offset)
        return `${propertyKey(operation.id)}: defineOffsetQuery({ operation: ${op}, input: ${name}, offset: ${JSON.stringify(binding.offset)}, fields: ${JSON.stringify({ offset: binding.responseOffset, limit: binding.responseLimit, total: binding.total, items: binding.items })}, page: page => ({ offset: page[${JSON.stringify(binding.responseOffset)}], limit: page[${JSON.stringify(binding.responseLimit)}], total: page[${JSON.stringify(binding.total)}], items: page[${JSON.stringify(binding.items)}] }), bodyCache: true, ...runtime, client: ${JSON.stringify(client.name)}, operationId: ${JSON.stringify(operation.id)} })`;
      return `${propertyKey(operation.id)}: defineInfiniteQuery({ operation: ${op}, input: ${name}, cursor: ${JSON.stringify(binding.cursor)}, nextCursor: page => page[${JSON.stringify(binding.nextCursor)}], items: page => page[${JSON.stringify(binding.items)}], bodyCache: true, ...runtime, client: ${JSON.stringify(client.name)}, operationId: ${JSON.stringify(operation.id)} })`;
    },
  );
  const infinite = client.infiniteQueries.length > 0;
  const factories = ['queryConfig'];
  const types = ['QueryConfig'];
  if (client.queries.length > 0) {
    factories.push('defineQuery');
    types.push('QueryFactories');
  }
  if (infinite) {
    if (client.infiniteQueries.some(({ binding }) => 'cursor' in binding))
      factories.push('defineInfiniteQuery');
    if (client.infiniteQueries.some(({ binding }) => 'offset' in binding))
      factories.push('defineOffsetQuery');
    types.push('InfiniteQueryFactoryFor');
  }
  const selectedOperations = new Set([
    ...client.queries.map((operation) => operationScope(operation.id)),
    ...client.infiniteQueries.map(({ operation }) =>
      operationScope(operation.id),
    ),
  ]);
  const imports = [
    `import { ${[...selectedOperations].sort().join(', ')} } from './client.${client.name}.operations.ts';`,
    `import { ${factories.join(', ')} } from './query-runtime.ts';`,
    `import type { ${types.join(', ')} } from './query-runtime.ts';`,
    ...(infinite ? [zodImport] : []),
    zodTypeImports(renderer.typeImports),
    ...(schemaImports.size
      ? [
          `import { ${[...schemaImports].sort().join(', ')} } from './client.${client.name}.schemas.ts';`,
        ]
      : []),
    ...(usesSchemaTypes
      ? [`import type * as schemas from './client.${client.name}.schemas.ts';`]
      : []),
    helperImports(renderer.helpers),
  ].join('\n');
  return `${banner}
    ${imports}
    ${renderer.takeDeclarations()}
    ${inputs.join('\n')}
    export { QueryResponseError } from './query-runtime.ts';
    export { shareQueryData } from './query-sharing.ts';
    export type { CacheContext, QueryConfig, QueryExecutor, Execution, ResponseInspection, ValidatedResponse, CancellationEvent, CancellationMapper, OperationInvalidationFilter, TypedQueryResponseError } from './query-runtime.ts';
    ${
      client.queries.length
        ? `
    export function createQueries(config: QueryConfig): QueryFactories<{ ${selectedTypes} }> {
      const runtime = queryConfig(config);
      return Object.freeze({ ${entries.join(',')} });
    }`
        : ''
    }
    ${
      infinite
        ? `
    export function createInfiniteQueries(config: QueryConfig): Readonly<{ ${infiniteTypes.join('\n')} }> {
      const runtime = queryConfig(config);
      return Object.freeze({ ${infiniteEntries.join(',')} });
    }`
        : ''
    }`;
}

function renderStandalone(
  descriptor: Descriptor,
  selection: Standalone,
): string {
  const { renderer, declarations } = renderComponents(descriptor, [
    { direction: selection.direction, names: selection.schemaOrder },
  ]);
  const root = renderer.schema(
    selection.schema,
    selection.direction,
    `standalone.${selection.name}`,
    `standalone_${selection.name.replaceAll('-', '_h')}`,
    true,
  );
  return `${banner}
    ${renderer.usesZod() ? zodImport : ''}
    ${zodTypeImports(renderer.typeImports)}
    ${helperImports(renderer.helpers)}
    ${declarations}
    ${renderer.takeDeclarations()}
    export const schema = ${source(root, `standalone.${selection.name}`)};
    export type Input = import('zod').input<typeof schema>;
    export type Output = import('zod').output<typeof schema>;`;
}

export async function render(
  descriptor: Descriptor,
  clients: readonly Client[],
  standalone: readonly Standalone[],
): Promise<Readonly<Record<string, string>>> {
  const helper = await readFile(
    new URL('./runtime.ts', import.meta.url),
    'utf8',
  );
  const outputs: Record<string, string> = {
    'runtime.ts': `${banner}${helper}`,
  };
  if (clients.some((client) => client.execution))
    outputs['call-runtime.ts'] =
      `${banner}${await readFile(new URL('./call-runtime.ts', import.meta.url), 'utf8')}`;
  if (
    clients.some(
      (client) =>
        client.execution ||
        client.queries.length + client.infiniteQueries.length > 0,
    )
  )
    outputs['execution-runtime.ts'] =
      `${banner}${await readFile(new URL('./execution-runtime.ts', import.meta.url), 'utf8')}`;
  if (
    clients.some(
      (client) => client.queries.length + client.infiniteQueries.length > 0,
    )
  ) {
    for (const name of ['query-runtime.ts', 'query-sharing.ts'])
      outputs[name] =
        `${banner}${await readFile(new URL(name, import.meta.url), 'utf8')}`;
  }
  if (
    clients.some(
      (client) =>
        client.target === 'browser' &&
        client.operations.some(
          (operation) => operation.body.kind === 'multipart',
        ),
    )
  )
    outputs['runtime.browser.ts'] =
      `${banner}${await readFile(new URL('./runtime.browser.ts', import.meta.url), 'utf8')}`;
  for (const client of clients)
    Object.assign(outputs, renderClient(descriptor, client));
  for (const selection of standalone)
    outputs[`standalone.${selection.name}.ts`] = renderStandalone(
      descriptor,
      selection,
    );
  const rendered = await Promise.all(
    Object.entries(outputs).map(async ([name, source]) => {
      // Keep generated bytes independent of cwd, consumer formatter settings and
      // import reordering. Formatting validates the complete set before any write.
      const result = await format(name, source, {
        printWidth: 80,
        singleQuote: true,
        trailingComma: 'all',
        semi: true,
        endOfLine: 'lf',
        tabWidth: 2,
        useTabs: false,
        sortImports: false,
        embeddedLanguageFormatting: 'off',
      });
      if (result.errors.length > 0)
        fail(
          `generated ${name}`,
          `Oxfmt could not format TypeScript: ${result.errors.map((error) => error.message).join('; ')}`,
        );
      return [name, result.code] as const;
    }),
  );
  return Object.freeze(Object.fromEntries(rendered));
}
