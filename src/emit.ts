const banner = '// Generated by Pomegranate. Do not edit.\n';

// `.d.ts` is a declaration file, and the formatter also treats `.d.` path
// segments as declarations. `_d` cannot collide with a legal selection name,
// whose first character must be a lowercase letter. Identities stay unchanged.
function moduleName(name: string): string {
  return name === 'd' ? '_d' : name;
}
type Entries = [string | number, Expression][];

function operationScope(id: string): string {
  // Escape the marker as well as punctuation so original IDs and role suffixes
  // cannot alias: read-options, read_options and read_x2d_options stay distinct.
  // The hex terminator distinguishes a.1 from a\u02e1 even beside hex digits.
  // Preserve existing ASCII symbols; names never depend on selection or order.
  return `operation_${id.replace(/[^A-Za-z0-9]/gu, (character) =>
    character === '_' ? '_u' : `_x${character.codePointAt(0)!.toString(16)}_`,
  )}`;
}

// Source consumers resolve real TypeScript files; JavaScript emission rewrites
// their extensions instead of requiring bundler-specific resolver aliases.
function helperImports(helpers: ReadonlySet<string>): string {
  const shared = [...helpers].filter((name) => name !== 'browserFile').sort();
  return [
    shared.length ? `import {${shared.join(',')}} from './runtime.ts';` : '',
    helpers.has('browserFile')
      ? "import {browserFile} from './runtime.browser.ts';"
      : '',
  ].join('\n');
}

function runtimeTypeImports(imports: ReadonlySet<string>): string {
  return imports.size
    ? `import type { ${[...imports].sort().join(', ')} } from './runtime.ts';`
    : '';
}

function renderComponents(
  descriptor: Descriptor,
  selections: readonly { direction: Direction; names: readonly string[] }[],
  componentType: ReturnType<typeof renderTypes>,
  target?: Client['target'],
  exportValidators = false,
) {
  const renderer = schemaRenderer(
    descriptor.schemas,
    (name, direction) => identifier(parseSymbol(name, direction)),
    (name, direction) => componentType(name, direction, target),
    target,
  );
  const declarations = selections.flatMap(({ direction, names }) =>
    names.map((name) => {
      const schema = descriptor.schemas[direction].get(name)!;
      const parse = parseSymbol(name, direction);
      const type = typeSymbol(name, direction);
      const location = `components.schemas.${name}`;
      if (
        exportValidators ||
        schema.kind !== 'ref' ||
        hasConstraints(schema.constraints)
      )
        renderer.push(
          `type ${type} = ${componentType(name, direction, target)};`,
          location,
        );
      renderer.define(
        schema,
        direction,
        location,
        parse,
        parse,
        type,
        exportValidators,
      );
      return renderer.takeDeclarations();
    }),
  );
  return { renderer, declarations: declarations.join('\n') };
}

function bodyRequired(body: Operation['body']): boolean {
  return body.kind === 'multipart' || (body.kind !== 'none' && body.required);
}

// Request options are one strict object of strict parameter groups and the
// body. The explicit structural return type is what `build` accepts.
function parameterOptions(
  operation: Operation,
  parameters: Operation['parameters'],
  renderer: SchemaRenderer,
  scope: string,
  headers?: ReadonlyMap<string, Expression>,
): { parse: Expression; type: string } {
  const fields: ObjectField[] = [];
  const types: string[] = [];
  const requiredBody = bodyRequired(operation.body);
  let required = requiredBody;
  for (const [position, field] of [
    ['path', 'path'],
    ['query', 'query'],
    ['header', 'headers'],
  ] as const) {
    const group = parameters.filter((parameter) => parameter.in === position);
    if (group.length === 0) continue;
    const requiredGroup = group.some((parameter) => parameter.required);
    required ||= requiredGroup;
    const groupType = `{${group
      .map(
        (parameter) =>
          `${propertyKey(parameter.name)}${parameter.required ? '' : '?'}: ${renderer.typeOf(parameter.schema, 'request')}${parameter.required ? '' : ' | undefined'};`,
      )
      .join('')}}`;
    const name = `${scope}_${position}`;
    renderer.objectParser(
      name,
      groupType,
      group.map((parameter, index) => ({
        name: parameter.name,
        required: parameter.required,
        parse:
          (position === 'header' ? headers?.get(parameter.name) : undefined) ??
          renderer.part(
            parameter.schema,
            'request',
            `${operation.id}.parameters.${parameter.name}`,
            `${scope}_${position}_${index}`,
          ),
      })),
      true,
    );
    fields.push({
      name: field,
      required: requiredGroup,
      parse: identifier(name),
    });
    types.push(
      `${field}${requiredGroup ? '' : '?'}: ${groupType}${requiredGroup ? '' : ' | undefined'};`,
    );
  }
  if (operation.body.kind !== 'none') {
    fields.push({
      name: 'body',
      required: requiredBody,
      parse: renderer.part(
        operation.body.schema,
        'request',
        `${operation.id}.requestBody`,
        `${scope}_body`,
      ),
    });
    types.push(
      `body${requiredBody ? '' : '?'}: ${renderer.typeOf(operation.body.schema, 'request')}${requiredBody ? '' : ' | undefined'};`,
    );
  }
  const value = fields.length ? `{${types.join('')}}` : 'Record<string, never>';
  const type = required ? value : `${value} | undefined`;
  const inner = required ? scope : `${scope}_value`;
  if (fields.length) renderer.objectParser(inner, value, fields, true);
  else if (required) fail(operation.id, 'required options need a field');
  if (required) return { parse: identifier(inner), type };
  renderer.typeImports.add('Issues');
  renderer.typeImports.add('Invalid');
  const value_ = fields.length ? inner : renderer.use('emptyOptions').source;
  renderer.push(
    `function ${scope}(input: unknown, issues: Issues): ${type} | Invalid {
      return input === undefined ? undefined : ${value_}(input, issues);
    }`,
  );
  return { parse: identifier(scope), type };
}

function requestHeaders(operation: Operation, renderer: SchemaRenderer) {
  const schemas = new Map<string, Expression>();
  const specs = object(
    operation.parameters
      .filter((parameter) => parameter.in === 'header')
      .map((header, index): Entries[number] => {
        const scope = `${operationScope(operation.id)}_header_${index}`;
        const location = `${operation.id}.headers.${header.name}`;
        // Both validation stages use one parser, declared before the options.
        const schema = renderer.part(header.schema, 'request', location, scope);
        schemas.set(header.name, schema);
        return [
          header.name.toLowerCase(),
          object([
            ['required', literal(header.required)],
            ['schema', schema],
          ]),
        ];
      }),
  );
  return { schemas, specs };
}

function responseSpecs(
  operation: Operation,
  renderer: SchemaRenderer,
): { expression: Expression; type: string } {
  const types: string[] = [];
  const expression = object(
    operation.responses.map((response) => {
      const prefix = `${operationScope(operation.id)}_response_${response.status}`;
      const headerTypes: string[] = [];
      const headers = object(
        response.headers.map((header, index) => {
          const parse = renderer.part(
            header.schema,
            'response',
            `${operation.id}.responses.${response.status}.headers.${header.name}`,
            `${prefix}_header_${index}`,
          );
          headerTypes.push(
            `readonly ${propertyKey(header.name)}: { readonly required: ${header.required}; readonly schema: typeof ${parse.source} };`,
          );
          return [
            header.name,
            object([
              ['required', literal(header.required)],
              ['schema', parse],
            ]),
          ];
        }),
      );
      const entries: Entries = [
        ['bodyKind', literal(response.body.kind)],
        ['headers', headers],
      ];
      let schemaType = '';
      if (response.body.kind !== 'none') {
        const contentTypes: string[] = [];
        entries.push([
          'content',
          object(
            [...response.body.content].map(([mediaType, representation]) => {
              const parse = renderer.part(
                representation.schema,
                'response',
                `${operation.id}.responses.${response.status}.content.${mediaType}`,
                prefix,
              );
              contentTypes.push(
                `readonly ${propertyKey(mediaType)}: {readonly bodyKind: '${representation.kind}'; readonly schema: typeof ${parse.source};};`,
              );
              return [
                mediaType,
                object([
                  ['bodyKind', literal(representation.kind)],
                  ['schema', parse],
                ]),
              ];
            }),
          ),
        ]);
        schemaType = `readonly content: {${contentTypes.join('')}};`;
      }
      types.push(
        `readonly ${response.status}: { readonly bodyKind: '${response.body.kind}'; readonly headers: { ${headerTypes.join('')} }; ${schemaType} };`,
      );
      return [response.status, object(entries)];
    }),
  );
  return { expression, type: `{${types.join('')}}` };
}

function operationExpression(
  operation: Operation,
  client: Client,
  renderer: SchemaRenderer,
): { expression: Expression; type: string } {
  const headers = requestHeaders(operation, renderer);
  const parameters = operation.parameters.filter(
    (parameter) =>
      parameter.in !== 'header' ||
      !client.transportHeaders.includes(parameter.name.toLowerCase()),
  );
  const options = parameterOptions(
    operation,
    parameters,
    renderer,
    `${operationScope(operation.id)}_options`,
    headers.schemas,
  );
  const responses = responseSpecs(operation, renderer);
  const entries: Entries = [
    ['operationId', literal(operation.id)],
    ['method', literal(operation.method)],
    ['path', literal(operation.path)],
    ['security', data(operation.security)],
    ['policy', data(Object.fromEntries(operation.policy))],
    ['bodyKind', literal(operation.body.kind)],
    [
      'parameters',
      data(
        parameters.map(({ name, in: position, required, explode }) => ({
          name,
          in: position,
          required,
          ...(explode === false ? { explode } : {}),
        })),
      ),
    ],
    ['options', options.parse],
    ['headers', headers.specs],
    ['responses', responses.expression],
  ];
  if (operation.body.kind === 'multipart')
    entries.push(['multipart', data(operation.body.fields)]);
  else if (operation.body.kind !== 'none')
    entries.push(['contentType', literal(operation.body.contentType)]);
  renderer.typeImports.add('Operation');
  renderer.typeImports.add('Invalid');
  const bodyKind =
    (operation.body.kind === 'json' || operation.body.kind === 'text') &&
    !bodyRequired(operation.body)
      ? `'${operation.body.kind}' | 'none'`
      : `'${operation.body.kind}'`;
  return {
    expression: call(identifier('defineOperation'), [object(entries)]),
    // The named options parser already has a checked contract return. Refer to
    // it explicitly for isolated declarations without duplicating inline types.
    type: `Operation<Exclude<ReturnType<typeof ${options.parse.source}>, Invalid>, ${responses.type}, ${bodyKind}>`,
  };
}

function renderClient(
  descriptor: Descriptor,
  client: Client,
  addOutput: (name: string, source: string) => void,
  componentType: ReturnType<typeof renderTypes>,
): void {
  const selections = [
    { direction: 'request', names: client.requestSchemas },
    { direction: 'response', names: client.responseSchemas },
  ] as const;
  const { renderer: components, declarations } = renderComponents(
    descriptor,
    selections,
    componentType,
    client.target,
    true,
  );
  const schemaMaps = selections.map(({ direction, names }) => {
    const identity = parserIdentities(descriptor.schemas[direction]);
    // An explicit shape argument checks the literal once. Inferring Object.freeze's
    // T through the Readonly annotation re-checks every member several times.
    // Validators are created inside a function declaration: references there
    // do not make TypeScript walk control flow across the whole module.
    const shape = `type_${direction}Schemas`;
    // A true alias shares its target's validator instance, as the target's
    // parser itself; constrained references keep their own instance.
    const uses = new Map<string, number>();
    for (const name of names)
      uses.set(identity(name), (uses.get(identity(name)) ?? 0) + 1);
    const shared = [...uses].filter(([, count]) => count > 1).map(([id]) => id);
    const validator = names.length ? components.use('validator').source : '';
    if (names.length) components.typeImports.add('Validator');
    const create = (name: string) =>
      `${validator}(${parseSymbol(name, direction)})`;
    const expression = call(identifier(`Object.freeze<${shape}>`), [
      object(
        names.map((name) => [
          name,
          identifier(
            shared.includes(identity(name))
              ? `shared[${jsonSource(identity(name))}]`
              : create(identity(name)),
          ),
        ]),
      ),
    ]);
    const sharedDeclaration = shared.length
      ? `const shared = {${shared.map((id) => `${propertyKey(id)}: ${create(id)}`).join(',')}};`
      : '';
    const fields = names
      .map((name) => `${propertyKey(name)}: ${typeSymbol(name, direction)};`)
      .join('\n');
    // Preserve exact registry members when applications publish inferred bindings.
    const registryType = `{${names
      .map(
        (name) =>
          `${propertyKey(name)}: Validator<${typeSymbol(name, direction)}>;`,
      )
      .join('')}}`;
    // Exported so declaration emit for inferred application exports can name
    // the registry shape instead of expanding it (TS7056 on large clients).
    return `export type ${shape} = ${registryType};
      function make_${direction}Schemas(): Readonly<${shape}> {
        ${sharedDeclaration}
        return ${source(expression, `client.${moduleName(client.name)}.${direction}Schemas`)};
      }
      export const ${direction}Schemas: Readonly<${shape}> = /* @__PURE__ */ make_${direction}Schemas();
      export type ${direction === 'request' ? 'Request' : 'Response'}Types = {${fields}};`;
  });
  const emittedSchema = `${banner}
    ${runtimeTypeImports(components.typeImports)}
    ${helperImports(components.helpers)}
    ${declarations}
    ${schemaMaps.join('\n')}`;
  addOutput(`client.${moduleName(client.name)}.schemas.ts`, emittedSchema);
  const schemaImports = new Set<string>();
  let usesSchemaTypes = false;
  const inline = schemaRenderer(
    descriptor.schemas,
    (name, direction) => {
      const symbol = parseSymbol(name, direction);
      schemaImports.add(symbol);
      return identifier(symbol);
    },
    (name, direction) => {
      usesSchemaTypes = true;
      return `schemas.${direction === 'request' ? 'Request' : 'Response'}Types[${jsonSource(name)}]`;
    },
    client.target,
  );
  inline.helpers.add('defineOperation');
  // Internal named exports share the same instances as the public aggregates.
  // Query modules can retain selected operations without importing the registry.
  const accountOperations = sourceBudget();
  const operationDeclarations = client.operations.map((operation) => {
    const scope = operationScope(operation.id);
    const defined = operationExpression(operation, client, inline);
    const declaration = `function define_${scope}(): ${defined.type} {
        return ${source(defined.expression, `client.${moduleName(client.name)}.${operation.id}`)};
      }
      export const ${scope}: ReturnType<typeof define_${scope}> = /* @__PURE__ */ define_${scope}();`;
    // Policy strings can be shared in a small YAML input and repeated in every
    // operation. Bound these fragments before joining the operations module.
    accountOperations(
      declaration,
      `paths.${operation.path}.${operation.method.toLowerCase()}`,
    );
    return declaration;
  });
  const operations = call(identifier('Object.freeze<type_operations>'), [
    object(
      client.operations.map((operation) => [
        operation.id,
        identifier(operationScope(operation.id)),
      ]),
    ),
  ]);
  // Name existing operation types so declaration emission does not expand the
  // entire client again; large inferred aggregates exceed TS serialization limits.
  // ReturnType of a function declaration names each member without a typeof
  // query on a module variable, which would also walk module control flow.
  const operationsType = `{${client.operations
    .map(
      (operation) =>
        `${propertyKey(operation.id)}: ReturnType<typeof define_${operationScope(operation.id)}>;`,
    )
    .join('')}}`;
  const emittedOperations = `${banner}
    ${runtimeTypeImports(inline.typeImports)}
    ${helperImports(inline.helpers)}
    ${schemaImports.size ? `import { ${[...schemaImports].sort().join(', ')} } from './client.${moduleName(client.name)}.schemas.ts';` : ''}
    ${usesSchemaTypes ? `import type * as schemas from './client.${moduleName(client.name)}.schemas.ts';` : ''}
    ${inline.takeDeclarations()}
    ${operationDeclarations.join('\n')}
    export type type_operations = ${operationsType};
    function make_operations(): Readonly<type_operations> {
      return ${source(operations, `client.${moduleName(client.name)}.operations`)};
    }
    export const operations: Readonly<type_operations> = /* @__PURE__ */ make_operations();`;
  addOutput(
    `client.${moduleName(client.name)}.operations.ts`,
    emittedOperations,
  );
  const index = `${banner}
    export { operations } from './client.${moduleName(client.name)}.operations.ts';
    export type { RequestTypes, ResponseTypes } from './client.${moduleName(client.name)}.schemas.ts';
    export { RequestValidationError } from './runtime.ts';
    export type { PreparedRequest, Policy, Security, Responses, ProtocolResult, ProtocolFailure, ObservedResponse, HeaderContext, MultipartField } from './runtime.ts';
    ${
      client.execution
        ? `export { createClient, ResponseError } from './client.${moduleName(client.name)}.execute.ts';
    export type { Client, ClientConfig, Executor, Execution, ExecutionContext, ResponseInspection, ValidatedResponse, CancellationEvent, CancellationMapper, TypedResponseError } from './client.${moduleName(client.name)}.execute.ts';`
        : ''
    }`;
  addOutput(`client.${moduleName(client.name)}.ts`, index);
  if (client.execution)
    addOutput(
      `client.${moduleName(client.name)}.execute.ts`,
      renderExecution(client),
    );
  if (client.queries.length + client.infiniteQueries.length > 0)
    addOutput(
      `client.${moduleName(client.name)}.queries.ts`,
      renderQueries(descriptor, client),
    );
}

// Named member interfaces bound inferred application declaration exports. Keep
// their outer mapped Readonly: a bare interface changes the original maps'
// implicit assignment compatibility with Record<string, unknown>.
function renderExecution(client: Client): string {
  const account = sourceBudget();
  const entries = client.operations.map((operation) => {
    const member = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(operation.id)
      ? `.${operation.id}`
      : `[${jsonSource(operation.id)}]`;
    const entry = `${propertyKey(operation.id)}: defineCall({ operation: operations${member}, ...runtime, client: ${jsonSource(client.name)}, operationId: ${jsonSource(operation.id)} })`;
    account(entry, `paths.${operation.path}.${operation.method.toLowerCase()}`);
    return entry;
  });
  return `${banner}
    import { operations } from './client.${moduleName(client.name)}.operations.ts';
    import { defineCall } from './call-runtime.ts';
    import { executionConfig } from './execution-runtime.ts';
    import type { ClientConfig } from './execution-runtime.ts';
    import type { ExecutionClient } from './call-runtime.ts';
    export { ResponseError } from './execution-runtime.ts';
    export type { ClientConfig, Executor, Execution, ExecutionContext, ResponseInspection, ValidatedResponse, CancellationEvent, CancellationMapper, TypedResponseError } from './execution-runtime.ts';
    export interface ClientMembers extends ExecutionClient<typeof operations> {}
    export type Client = Readonly<ClientMembers>;
    export function createClient(config: ClientConfig): Client {
      const runtime = executionConfig(config);
      return Object.freeze({ ${entries.join(',')} });
    }`;
}

function renderQueries(descriptor: Descriptor, client: Client): string {
  const account = sourceBudget();
  const entry = (operation: Operation, source: string): string => {
    account(
      source,
      `paths.${operation.path}.${operation.method.toLowerCase()}`,
    );
    return source;
  };
  const selectedTypes = client.queries
    .map(
      (operation) =>
        `${propertyKey(operation.id)}: typeof ${operationScope(operation.id)};`,
    )
    .join('\n');
  const entries = client.queries.map((operation) =>
    entry(
      operation,
      `${propertyKey(operation.id)}: defineQuery({ operation: ${operationScope(operation.id)}, bodyCache: ${operation.responses.filter((response) => response.status >= 200 && response.status < 300).every((response) => response.body.kind !== 'none')}, ...runtime, client: ${jsonSource(client.name)}, operationId: ${jsonSource(operation.id)} })`,
    ),
  );
  // Removing cursors and transport headers can remove every schema reference
  // from base inputs, even when the ordinary client needs those components.
  const schemaImports = new Set<string>();
  let usesSchemaTypes = false;
  const renderer = schemaRenderer(
    descriptor.schemas,
    (name, direction) => {
      const symbol = parseSymbol(name, direction);
      schemaImports.add(symbol);
      return identifier(symbol);
    },
    (name, direction) => {
      usesSchemaTypes = true;
      return `schemas.${direction === 'request' ? 'Request' : 'Response'}Types[${jsonSource(name)}]`;
    },
    client.target,
  );
  const infiniteTypes: string[] = [];
  const infiniteEntries = client.infiniteQueries.map(
    ({ operation, binding }) => {
      const offset = binding.kind === 'offset';
      const name = `infinite_${operationScope(operation.id)}_input`;
      const parameters = operation.parameters.filter(
        (parameter) =>
          !(
            parameter.in === 'query' &&
            parameter.name === (offset ? binding.offset : binding.cursor)
          ) &&
          !(
            parameter.in === 'header' &&
            client.transportHeaders.includes(parameter.name.toLowerCase())
          ),
      );
      const input = parameterOptions(operation, parameters, renderer, name);
      const op = operationScope(operation.id);
      infiniteTypes.push(
        `${propertyKey(operation.id)}: InfiniteQueryFactoryFor<typeof ${op}, ${input.type}, ${jsonSource(binding.items)}${offset ? ', number' : ''}>;`,
      );
      if (offset)
        return entry(
          operation,
          `${propertyKey(operation.id)}: defineOffsetQuery({ operation: ${op}, input: ${name}, offset: ${jsonSource(binding.offset)}, fields: ${jsonSource({ offset: binding.responseOffset, limit: binding.responseLimit, total: binding.total, items: binding.items })}, page: page => ({ offset: page[${jsonSource(binding.responseOffset)}], limit: page[${jsonSource(binding.responseLimit)}], total: page[${jsonSource(binding.total)}], items: page[${jsonSource(binding.items)}] }), bodyCache: true, ...runtime, client: ${jsonSource(client.name)}, operationId: ${jsonSource(operation.id)} })`,
        );
      return entry(
        operation,
        `${propertyKey(operation.id)}: defineInfiniteQuery({ operation: ${op}, input: ${name}, cursor: ${jsonSource(binding.cursor)}, nextCursor: page => page[${jsonSource(binding.nextCursor)}], items: page => page[${jsonSource(binding.items)}], bodyCache: true, ...runtime, client: ${jsonSource(client.name)}, operationId: ${jsonSource(operation.id)} })`,
      );
    },
  );
  const infinite = client.infiniteQueries.length > 0;
  const factories = ['queryConfig'];
  const types = ['QueryConfig'];
  if (client.queries.length > 0) {
    factories.push('defineQuery');
    types.push('QueryFactories');
  }
  if (infinite) {
    if (client.infiniteQueries.some(({ binding }) => binding.kind === 'cursor'))
      factories.push('defineInfiniteQuery');
    if (client.infiniteQueries.some(({ binding }) => binding.kind === 'offset'))
      factories.push('defineOffsetQuery');
    types.push('InfiniteQueryFactoryFor');
  }
  const selectedOperations = new Set([
    ...client.queries.map((operation) => operationScope(operation.id)),
    ...client.infiniteQueries.map(({ operation }) =>
      operationScope(operation.id),
    ),
  ]);
  const imports = [
    `import { ${[...selectedOperations].sort().join(', ')} } from './client.${moduleName(client.name)}.operations.ts';`,
    `import { ${factories.join(', ')} } from './query-runtime.ts';`,
    `import type { ${types.join(', ')} } from './query-runtime.ts';`,
    runtimeTypeImports(renderer.typeImports),
    ...(schemaImports.size
      ? [
          `import { ${[...schemaImports].sort().join(', ')} } from './client.${moduleName(client.name)}.schemas.ts';`,
        ]
      : []),
    ...(usesSchemaTypes
      ? [
          `import type * as schemas from './client.${moduleName(client.name)}.schemas.ts';`,
        ]
      : []),
    helperImports(renderer.helpers),
  ].join('\n');
  return `${banner}
    ${imports}
    ${renderer.takeDeclarations()}
    export { QueryResponseError } from './query-runtime.ts';
    export { shareQueryData } from './query-sharing.ts';
    export type { CacheContext, QueryConfig, QueryExecutor, Execution, ResponseInspection, ValidatedResponse, CancellationEvent, CancellationMapper, OperationInvalidationFilter, TypedQueryResponseError } from './query-runtime.ts';
    ${
      client.queries.length
        ? `
    export interface QueryMembers extends QueryFactories<{ ${selectedTypes} }> {}
    export type Queries = Readonly<QueryMembers>;
    export function createQueries(config: QueryConfig): Queries {
      const runtime = queryConfig(config);
      return Object.freeze({ ${entries.join(',')} });
    }`
        : ''
    }
    ${
      infinite
        ? `
    export interface InfiniteQueryMembers extends Readonly<{ ${infiniteTypes.join('\n')} }> {}
    export type InfiniteQueries = Readonly<InfiniteQueryMembers>;
    export function createInfiniteQueries(config: QueryConfig): InfiniteQueries {
      const runtime = queryConfig(config);
      return Object.freeze({ ${infiniteEntries.join(',')} });
    }`
        : ''
    }`;
}

function renderStandalone(
  descriptor: Descriptor,
  selection: Standalone,
  componentType: ReturnType<typeof renderTypes>,
): string {
  const { renderer, declarations } = renderComponents(
    descriptor,
    [{ direction: selection.direction, names: selection.schemaOrder }],
    componentType,
  );
  const location = `standalone.${selection.name}`;
  const root = renderer.part(
    selection.schema,
    selection.direction,
    location,
    `standalone_${selection.name.replaceAll('-', '_h')}`,
  );
  renderer.typeImports.add('Validator');
  const validator = renderer.use('validator');
  return `${banner}
    ${runtimeTypeImports(renderer.typeImports)}
    ${helperImports(renderer.helpers)}
    ${declarations}
    ${renderer.takeDeclarations()}
    export type Input = ${renderer.typeOf(selection.schema, selection.direction)};
    export type Output = Input;
    export const schema: Validator<Output> = ${pureInitializer(call(validator, [root]), location)};`;
}

export async function render(
  descriptor: Descriptor,
  clients: readonly Client[],
  standalone: readonly Standalone[],
): Promise<Readonly<Record<string, string>>> {
  const helper = await readFile(
    new URL('./runtime.ts', import.meta.url),
    'utf8',
  );
  const policyTemplate = await readFile(
    new URL('./policy-types.ts', import.meta.url),
    'utf8',
  );
  // Requests and executor callbacks share the declaration. A build-only
  // generic would lose the application's enum labels at the executor boundary.
  const policyFields = [...descriptor.policy.fields].map(
    ([name, schema]) =>
      `readonly ${propertyKey(name)}${descriptor.policy.required.includes(name) ? '' : '?'}: ${schemaType(schema, 'request')};`,
  );
  const policyType = policyFields.length
    ? `Readonly<{${policyFields.join('\n')}}>`
    : 'Readonly<Record<string, never>>';
  const outputs = new Map<string, string>();
  const account = sourceBudget();
  const addOutput = (name: string, source: string): void => {
    // Admit each complete module as it finishes, before rendering the next.
    // Renderer declaration budgets separately guard construction within one.
    account(source, `generated ${name}`);
    outputs.set(name, source);
  };
  addOutput('runtime.ts', `${banner}${helper}`);
  addOutput(
    'policy-types.ts',
    `${banner}${policyTemplate.replace(/export type Policy =[\s\S]*$/, () => `export type Policy = ${policyType};\n`)}`,
  );
  if (clients.some((client) => client.execution))
    addOutput(
      'call-runtime.ts',
      `${banner}${await readFile(new URL('./call-runtime.ts', import.meta.url), 'utf8')}`,
    );
  if (
    clients.some(
      (client) =>
        client.execution ||
        client.queries.length + client.infiniteQueries.length > 0,
    )
  )
    addOutput(
      'execution-runtime.ts',
      `${banner}${await readFile(new URL('./execution-runtime.ts', import.meta.url), 'utf8')}`,
    );
  if (
    clients.some(
      (client) => client.queries.length + client.infiniteQueries.length > 0,
    )
  ) {
    for (const name of ['query-runtime.ts', 'query-sharing.ts'])
      addOutput(
        name,
        `${banner}${await readFile(new URL(name, import.meta.url), 'utf8')}`,
      );
  }
  if (
    clients.some(
      (client) =>
        client.target === 'browser' &&
        client.operations.some(
          (operation) => operation.body.kind === 'multipart',
        ),
    )
  )
    addOutput(
      'runtime.browser.ts',
      `${banner}${await readFile(new URL('./runtime.browser.ts', import.meta.url), 'utf8')}`,
    );
  const componentType = renderTypes(
    descriptor,
    clients,
    standalone,
    (name, source) => addOutput(name, `${banner}${source}`),
  );
  for (const client of clients)
    renderClient(descriptor, client, addOutput, componentType);
  for (const selection of standalone)
    addOutput(
      `standalone.${moduleName(selection.name)}.ts`,
      renderStandalone(descriptor, selection, componentType),
    );
  const entries = [...outputs];
  const rendered: [string, string][] = [];
  for (const [name, source] of entries) {
    // Keep generated bytes independent of cwd, consumer formatter settings and
    // import reordering. Formatting validates the complete set before any write.
    const result = await format('generated.ts', source, {
      printWidth: 80,
      singleQuote: true,
      trailingComma: 'all',
      semi: true,
      endOfLine: 'lf',
      tabWidth: 2,
      useTabs: false,
      sortImports: false,
      embeddedLanguageFormatting: 'off',
    });
    if (result.errors.length > 0)
      fail(
        `generated ${name}`,
        `Oxfmt could not format TypeScript: ${result.errors.map((error) => error.message).join('; ')}`,
      );
    rendered.push([name, result.code]);
  }
  return Object.freeze(Object.fromEntries(rendered));
}
