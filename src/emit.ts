import { readFile } from 'node:fs/promises';
import { format } from 'oxfmt';
import {
  call,
  data,
  identifier,
  literal,
  member,
  method,
  object,
  source,
} from './code.js';
import type { Expression } from './code.js';
import { fail } from './diagnostics.js';
import { schemaRenderer } from './emit-schema.js';
import type { SchemaRenderer } from './emit-schema.js';
import type {
  Client,
  Descriptor,
  Direction,
  Operation,
  Standalone,
} from './model.js';
import {
  schemaSymbol,
  schemaType,
  typeSymbol,
  validatorType,
} from './schema-types.js';

const banner = '// Generated by Pomegranate. Do not edit.\n';
type Entries = [string | number, Expression][];

function operationScope(id: string): string {
  // IDs contain ASCII letters, digits and underscores. Escape every underscore
  // so an ID cannot absorb a role suffix: read_options headers must not collide
  // with read's options headers. Escaping the escape marker also distinguishes
  // read_uoptions. Names depend only on this operation, not generation order.
  return `operation_${id.replaceAll('_', '_u')}`;
}

// Source consumers resolve real TypeScript files; JavaScript emission rewrites
// their extensions instead of requiring bundler-specific resolver aliases.
function helperImports(helpers: ReadonlySet<string>): string {
  const shared = [...helpers].filter((name) => name !== 'browserFile').sort();
  return [
    shared.length ? `import {${shared.join(',')}} from './runtime.ts';` : '',
    helpers.has('browserFile')
      ? "import {browserFile} from './runtime.browser.ts';"
      : '',
  ].join('\n');
}

function renderComponents(
  descriptor: Descriptor,
  selections: readonly { direction: Direction; names: readonly string[] }[],
  target?: Client['target'],
) {
  const renderer = schemaRenderer(
    descriptor.schemas,
    (name, direction) => identifier(schemaSymbol(name, direction)),
    typeSymbol,
    target,
  );
  const declarations = selections.flatMap(({ direction, names }) =>
    names.map((name) => {
      const schema = descriptor.schemas[name]!;
      const symbol = schemaSymbol(name, direction);
      const type = typeSymbol(name, direction);
      const expression = renderer.schema(
        schema,
        direction,
        `components.schemas.${name}`,
        symbol,
      );
      return `type ${type} = ${schemaType(schema, direction, target)};
      ${renderer.takeDeclarations()}
      const ${symbol}: ${validatorType(schema, type, descriptor.schemas)} = ${source(expression, `components.schemas.${name}`)};`;
    }),
  );
  return { renderer, declarations: declarations.join('\n') };
}

function parameterOptions(
  operation: Operation,
  parameters: Operation['parameters'],
  renderer: SchemaRenderer,
) {
  const entries: Entries = [];
  let required = operation.body.kind !== 'none';
  for (const [position, field] of [
    ['path', 'path'],
    ['query', 'query'],
    ['header', 'headers'],
  ] as const) {
    const group = parameters.filter((parameter) => parameter.in === position);
    if (group.length === 0) continue;
    const requiredGroup = group.some((parameter) => parameter.required);
    required ||= requiredGroup;
    const fields: Entries = group.map((parameter, index) => {
      const schema = renderer.schema(
        parameter.schema,
        'request',
        `${operation.id}.parameters.${parameter.name}`,
        `${operationScope(operation.id)}_options_${position}_${index}`,
        true,
      );
      return [
        parameter.name,
        parameter.required ? schema : method(schema, 'optional'),
      ];
    });
    const schema = method(
      method(identifier('z'), 'object', [object(fields)]),
      'strict',
    );
    entries.push([field, requiredGroup ? schema : method(schema, 'optional')]);
  }
  if (operation.body.kind !== 'none')
    entries.push([
      'body',
      renderer.schema(
        operation.body.schema,
        'request',
        `${operation.id}.requestBody`,
        `${operationScope(operation.id)}_body`,
        true,
      ),
    ]);
  if (entries.length === 0) renderer.helpers.add('recordSchema');
  const options =
    entries.length === 0
      ? call(identifier('recordSchema'), [method(identifier('z'), 'never')])
      : method(method(identifier('z'), 'object', [object(entries)]), 'strict');
  return required ? options : method(options, 'optional');
}

function requestHeaderSpecs(
  operation: Operation,
  renderer: SchemaRenderer,
): Expression {
  return object(
    operation.parameters
      .filter((parameter) => parameter.in === 'header')
      .map((header, index) => [
        header.name.toLowerCase(),
        object([
          ['required', literal(header.required)],
          [
            'schema',
            renderer.schema(
              header.schema,
              'request',
              `${operation.id}.headers.${header.name}`,
              `${operationScope(operation.id)}_header_${index}`,
              true,
            ),
          ],
        ]),
      ]),
  );
}

function responseSpecs(
  operation: Operation,
  renderer: SchemaRenderer,
): Expression {
  return object(
    operation.responses.map((response) => {
      const prefix = `${operationScope(operation.id)}_response_${response.status}`;
      const headers = object(
        response.headers.map((header, index) => [
          header.name,
          object([
            ['required', literal(header.required)],
            [
              'schema',
              renderer.schema(
                header.schema,
                'response',
                `${operation.id}.responses.${response.status}.headers.${header.name}`,
                `${prefix}_header_${index}`,
                true,
              ),
            ],
          ]),
        ]),
      );
      const entries: Entries = [
        ['bodyKind', literal(response.body.kind)],
        ['headers', headers],
      ];
      if (response.body.kind === 'json')
        entries.push([
          'schema',
          renderer.schema(
            response.body.schema,
            'response',
            `${operation.id}.responses.${response.status}.body`,
            prefix,
            true,
          ),
        ]);
      return [response.status, object(entries)];
    }),
  );
}

function operationExpression(
  operation: Operation,
  client: Client,
  renderer: SchemaRenderer,
): Expression {
  const parameters = operation.parameters.filter(
    (parameter) =>
      parameter.in !== 'header' ||
      !client.transportHeaders.includes(parameter.name.toLowerCase()),
  );
  const entries: Entries = [
    ['operationId', literal(operation.id)],
    ['method', literal(operation.method)],
    ['path', literal(operation.path)],
    ['policy', data(operation.policy)],
    ['bodyKind', literal(operation.body.kind)],
    [
      'parameters',
      data(
        parameters.map(({ name, in: position, required }) => ({
          name,
          in: position,
          required,
        })),
      ),
    ],
    ['options', parameterOptions(operation, parameters, renderer)],
    ['headers', requestHeaderSpecs(operation, renderer)],
    ['responses', responseSpecs(operation, renderer)],
  ];
  if (operation.body.kind === 'multipart')
    entries.push(['multipart', data(operation.body.fields)]);
  return call(identifier('defineOperation'), [object(entries)]);
}

function renderClient(
  descriptor: Descriptor,
  client: Client,
): Readonly<Record<string, string>> {
  const selections = [
    { direction: 'request', names: client.requestSchemas },
    { direction: 'response', names: client.responseSchemas },
  ] as const;
  const { renderer: components, declarations } = renderComponents(
    descriptor,
    selections,
    client.target,
  );
  const schemaMaps = selections.map(({ direction, names }) => {
    const expression = method(identifier('Object'), 'freeze', [
      object(
        names.map((name) => [name, identifier(schemaSymbol(name, direction))]),
      ),
    ]);
    const fields = names
      .map(
        (name) => `[${JSON.stringify(name)}]: ${typeSymbol(name, direction)};`,
      )
      .join('\n');
    return `export const ${direction}Schemas = ${source(expression, `client.${client.name}.${direction}Schemas`)};
      export type ${direction === 'request' ? 'Request' : 'Response'}Types = {${fields}};`;
  });
  const emittedSchema = `${banner}
    ${components.usesZod() ? "import { z } from 'zod';" : ''}
    ${helperImports(components.helpers)}
    ${declarations}
    ${schemaMaps.join('\n')}`;
  const inline = schemaRenderer(
    descriptor.schemas,
    (name, direction) =>
      member(
        member(identifier('schemas'), `${direction}Schemas`),
        literal(name),
      ),
    (name, direction) =>
      `schemas.${direction === 'request' ? 'Request' : 'Response'}Types[${JSON.stringify(name)}]`,
    client.target,
  );
  inline.helpers.add('defineOperation');
  const operations = method(identifier('Object'), 'freeze', [
    object(
      client.operations.map((operation) => [
        operation.id,
        operationExpression(operation, client, inline),
      ]),
    ),
  ]);
  const hasReferences =
    client.requestSchemas.length + client.responseSchemas.length > 0;
  const emittedOperations = `${banner}import { z } from 'zod';
    ${helperImports(inline.helpers)}
    ${hasReferences ? `import * as schemas from './client.${client.name}.schemas.ts';` : ''}
    ${inline.takeDeclarations()}
    export const operations = ${source(operations, `client.${client.name}.operations`)};`;
  const index = `${banner}
    export { operations } from './client.${client.name}.operations.ts';
    export type { RequestTypes, ResponseTypes } from './client.${client.name}.schemas.ts';
    export { RequestValidationError } from './runtime.ts';
    export type { PreparedRequest, Responses, ProtocolResult, ProtocolFailure, ObservedResponse, HeaderContext, MultipartField } from './runtime.ts';`;
  return {
    [`client.${client.name}.schemas.ts`]: emittedSchema,
    [`client.${client.name}.operations.ts`]: emittedOperations,
    [`client.${client.name}.ts`]: index,
    ...(client.queries.length + client.infiniteQueries.length > 0
      ? {
          [`client.${client.name}.queries.ts`]: renderQueries(
            descriptor,
            client,
          ),
        }
      : {}),
  };
}

function renderQueries(descriptor: Descriptor, client: Client): string {
  const selected = client.queries
    .map((operation) => JSON.stringify(operation.id))
    .join(' | ');
  const entries = client.queries.map(
    (operation) =>
      `[${JSON.stringify(operation.id)}]: defineQuery({ operation: operations[${JSON.stringify(operation.id)}], execute, namespace, client: ${JSON.stringify(client.name)}, operationId: ${JSON.stringify(operation.id)} })`,
  );
  // Removing cursors and transport headers can remove every schema reference
  // from base inputs, even when the ordinary client needs those components.
  let usesReferences = false;
  const renderer = schemaRenderer(
    descriptor.schemas,
    (name, direction) => {
      usesReferences = true;
      return member(
        member(identifier('schemas'), `${direction}Schemas`),
        literal(name),
      );
    },
    (name, direction) =>
      `schemas.${direction === 'request' ? 'Request' : 'Response'}Types[${JSON.stringify(name)}]`,
    client.target,
  );
  const inputs: string[] = [];
  const infiniteTypes: string[] = [];
  const infiniteEntries = client.infiniteQueries.map(
    ({ operation, binding }) => {
      const name = `infinite_${operationScope(operation.id)}_input`;
      const parameters = operation.parameters.filter(
        (parameter) =>
          !(parameter.in === 'query' && parameter.name === binding.cursor) &&
          !(
            parameter.in === 'header' &&
            client.transportHeaders.includes(parameter.name.toLowerCase())
          ),
      );
      inputs.push(
        `const ${name} = ${source(parameterOptions(operation, parameters, renderer), `infiniteQueries.${client.name}.${operation.id}`)};`,
      );
      const op = `operations[${JSON.stringify(operation.id)}]`;
      infiniteTypes.push(
        `[${JSON.stringify(operation.id)}]: InfiniteQueryFactoryFor<typeof ${op}, z.input<typeof ${name}>, ${JSON.stringify(binding.items)}>;`,
      );
      return `[${JSON.stringify(operation.id)}]: defineInfiniteQuery({ operation: ${op}, input: ${name}, cursor: ${JSON.stringify(binding.cursor)}, nextCursor: page => page.data[${JSON.stringify(binding.nextCursor)}], items: page => page.data[${JSON.stringify(binding.items)}], execute, namespace, client: ${JSON.stringify(client.name)}, operationId: ${JSON.stringify(operation.id)} })`;
    },
  );
  const infinite = client.infiniteQueries.length > 0;
  const factories = ['queryConfig'];
  const types = ['QueryExecutor'];
  if (client.queries.length > 0) {
    factories.push('defineQuery');
    types.push('QueryFactories');
  }
  if (infinite) {
    factories.push('defineInfiniteQuery');
    types.push('InfiniteQueryFactoryFor');
  }
  const imports = [
    `import { operations } from './client.${client.name}.operations.ts';`,
    `import { ${factories.join(', ')} } from './query-runtime.ts';`,
    `import type { ${types.join(', ')} } from './query-runtime.ts';`,
    ...(infinite ? ["import { z } from 'zod';"] : []),
    ...(usesReferences
      ? [`import * as schemas from './client.${client.name}.schemas.ts';`]
      : []),
    helperImports(renderer.helpers),
  ].join('\n');
  return `${banner}
    ${imports}
    ${renderer.takeDeclarations()}
    ${inputs.join('\n')}
    export { QueryResponseError } from './query-runtime.ts';
    export { shareQueryData } from './query-sharing.ts';
    export type { CacheContext, QueryExecutor, TypedQueryResponseError } from './query-runtime.ts';
    ${
      client.queries.length
        ? `
    export function createQueries(config: Readonly<{ namespace: string; execute: QueryExecutor }>): QueryFactories<Pick<typeof operations, ${selected}>> {
      const { namespace, execute } = queryConfig(config);
      return Object.freeze({ ${entries.join(',')} });
    }`
        : ''
    }
    ${
      infinite
        ? `
    export function createInfiniteQueries(config: Readonly<{ namespace: string; execute: QueryExecutor }>): Readonly<{ ${infiniteTypes.join('\n')} }> {
      const { namespace, execute } = queryConfig(config);
      return Object.freeze({ ${infiniteEntries.join(',')} });
    }`
        : ''
    }`;
}

function renderStandalone(
  descriptor: Descriptor,
  selection: Standalone,
): string {
  const { renderer, declarations } = renderComponents(descriptor, [
    { direction: selection.direction, names: selection.schemaOrder },
  ]);
  const root = renderer.schema(
    selection.schema,
    selection.direction,
    `standalone.${selection.name}`,
    `standalone_${selection.name.replaceAll('-', '_h')}`,
    true,
  );
  return `${banner}
    ${renderer.usesZod() ? "import { z } from 'zod';" : ''}
    ${helperImports(renderer.helpers)}
    ${declarations}
    ${renderer.takeDeclarations()}
    export const schema = ${source(root, `standalone.${selection.name}`)};
    export type Input = import('zod').input<typeof schema>;
    export type Output = import('zod').output<typeof schema>;`;
}

export async function render(
  descriptor: Descriptor,
  clients: readonly Client[],
  standalone: readonly Standalone[],
): Promise<Readonly<Record<string, string>>> {
  const helper = await readFile(
    new URL('./runtime.ts', import.meta.url),
    'utf8',
  );
  const outputs: Record<string, string> = {
    'runtime.ts': `${banner}${helper}`,
  };
  if (
    clients.some(
      (client) => client.queries.length + client.infiniteQueries.length > 0,
    )
  ) {
    for (const name of ['query-runtime.ts', 'query-sharing.ts'])
      outputs[name] =
        `${banner}${await readFile(new URL(name, import.meta.url), 'utf8')}`;
  }
  if (
    clients.some(
      (client) =>
        client.target === 'browser' &&
        client.operations.some(
          (operation) => operation.body.kind === 'multipart',
        ),
    )
  )
    outputs['runtime.browser.ts'] =
      `${banner}${await readFile(new URL('./runtime.browser.ts', import.meta.url), 'utf8')}`;
  for (const client of clients)
    Object.assign(outputs, renderClient(descriptor, client));
  for (const selection of standalone)
    outputs[`standalone.${selection.name}.ts`] = renderStandalone(
      descriptor,
      selection,
    );
  const rendered = await Promise.all(
    Object.entries(outputs).map(async ([name, source]) => {
      // Keep generated bytes independent of cwd, consumer formatter settings and
      // import reordering. Formatting validates the complete set before any write.
      const result = await format(name, source, {
        printWidth: 80,
        singleQuote: true,
        trailingComma: 'all',
        semi: true,
        endOfLine: 'lf',
        tabWidth: 2,
        useTabs: false,
        sortImports: false,
        embeddedLanguageFormatting: 'off',
      });
      if (result.errors.length > 0)
        fail(
          `generated ${name}`,
          `Oxfmt could not format TypeScript: ${result.errors.map((error) => error.message).join('; ')}`,
        );
      return [name, result.code] as const;
    }),
  );
  return Object.freeze(Object.fromEntries(rendered));
}
