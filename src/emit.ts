import { readFile } from 'node:fs/promises';
import { format } from 'oxfmt';
import { fail } from './diagnostics.js';
import type { Client, Descriptor, Operation, Schema } from './model.js';

const banner = '// Generated by Pomegranate. Do not edit.\n';
const quote = (value: unknown): string => JSON.stringify(value);

function renderClient(
  descriptor: Descriptor,
  client: Client,
): Readonly<Record<string, string>> {
  const schemaOrder = descriptor.schemaOrder.filter(
    (name) =>
      client.requestSchemas.includes(name) ||
      client.responseSchemas.includes(name),
  );
  const indices = new Map(schemaOrder.map((name, index) => [name, index]));
  const schema = (
    value: Schema,
    direction: 'Request' | 'Response',
    imported = false,
  ): string => {
    if (value.kind === 'ref')
      return imported
        ? `schemas.${direction === 'Request' ? 'request' : 'response'}Schemas[${quote(value.name)}]`
        : `schema${indices.get(value.name)!}${direction}`;
    if (value.kind === 'object') {
      const properties = Object.entries(value.properties).map(
        ([name, child]) =>
          `${quote(name)}: ${schema(child, direction, imported)}${value.required.includes(name) ? '' : '.optional()'}`,
      );
      return `z.object({${properties.join(',')}})${direction === 'Request' ? '.strict()' : '.strip()'}`;
    }
    if (value.kind === 'array')
      return `z.array(${schema(value.items, direction, imported)})${value.minItems === undefined ? '' : `.min(${value.minItems})`}${value.maxItems === undefined ? '' : `.max(${value.maxItems})`}`;
    let expression: string;
    if (value.kind === 'string') {
      expression = 'z.string()';
      // OpenAPI counts Unicode code points, while Zod's length helpers use UTF-16
      // code units. Preserve the contract for astral characters as well.
      if (value.minLength !== undefined)
        expression += `.refine(value => [...value].length >= ${value.minLength}, ${quote(`expected at least ${value.minLength} Unicode characters`)})`;
      if (value.maxLength !== undefined)
        expression += `.refine(value => [...value].length <= ${value.maxLength}, ${quote(`expected at most ${value.maxLength} Unicode characters`)})`;
    } else if (value.kind === 'number' || value.kind === 'integer') {
      // Zod's .int() adds a safe-integer range that OpenAPI did not declare.
      expression =
        value.kind === 'integer'
          ? "z.number().refine(Number.isInteger, 'expected an integer')"
          : 'z.number()';
      if (value.minimum !== undefined) expression += `.min(${value.minimum})`;
      if (value.maximum !== undefined) expression += `.max(${value.maximum})`;
    } else expression = value.kind === 'null' ? 'z.null()' : 'z.boolean()';
    if (value.literals)
      expression += `.and(z.literal(${quote(value.literals.length === 1 ? value.literals[0] : value.literals)}))`;
    return expression;
  };
  const directions = [
    { direction: 'Request', names: client.requestSchemas },
    { direction: 'Response', names: client.responseSchemas },
  ] as const;
  const declarations = directions.flatMap(({ direction, names }) =>
    names.map(
      (name) =>
        `const schema${indices.get(name)!}${direction} = ${schema(descriptor.schemas[name]!, direction)};`,
    ),
  );
  const schemaMaps = directions.map(
    ({ direction, names }) =>
      `export const ${direction === 'Request' ? 'request' : 'response'}Schemas = Object.freeze({${names.map((name) => `${quote(name)}: schema${indices.get(name)!}${direction}`).join(',')}});`,
  );
  const emittedSchema = `${banner}${declarations.length ? "import { z } from 'zod';" : ''}\n${declarations.join('\n')}\n${schemaMaps.join('\n')}`;
  const operationSchema = (
    value: Schema,
    direction: 'Request' | 'Response',
  ): string => {
    // Operation-local schemas use the same renderer and reference component
    // bindings imported below, without reconstructing descriptor data.
    return schema(value, direction, true);
  };
  const emitOperation = (operation: Operation): string => {
    const parts: string[] = [];
    let requiredOptions = operation.body.kind === 'json';
    for (const [position, field] of [
      ['path', 'path'],
      ['query', 'query'],
      ['header', 'headers'],
    ] as const) {
      const parameters = operation.parameters.filter(
        (parameter) => parameter.in === position,
      );
      if (parameters.length === 0) continue;
      const required = parameters.some((parameter) => parameter.required);
      requiredOptions ||= required;
      const properties = parameters.map(
        (parameter) =>
          `${quote(parameter.name)}: ${operationSchema(parameter.schema, 'Request')}${parameter.required ? '' : '.optional()'}`,
      );
      parts.push(
        `${field}: z.object({${properties.join(',')}}).strict()${required ? '' : '.optional()'}`,
      );
    }
    if (operation.body.kind === 'json')
      parts.push(`body: ${operationSchema(operation.body.schema, 'Request')}`);
    const responses = operation.responses.map((response) => {
      const headerSpecs = response.headers.map(
        (header) =>
          `${quote(header.name)}: {required:${header.required},schema:${operationSchema(header.schema, 'Response')}}`,
      );
      return `${response.status}: {bodyKind: ${quote(response.body.kind)},${response.body.kind === 'json' ? `schema: ${operationSchema(response.body.schema, 'Response')},` : ''}headers:{${headerSpecs.join(',')}}}`;
    });
    const options =
      parts.length === 0
        ? 'z.record(z.string(), z.never())'
        : `z.object({${parts.join(',')}}).strict()`;
    return `${quote(operation.id)}: defineOperation({operationId:${quote(operation.id)},method:${quote(operation.method)},path:${quote(operation.path)},policy:${quote(operation.policy)},bodyKind:${quote(operation.body.kind)},parameters:${quote(operation.parameters.map(({ name, in: position }) => ({ name, in: position })))},options:${options}${requiredOptions ? '' : '.optional()'},responses:{${responses.join(',')}}})`;
  };
  const hasReferences = schemaOrder.length > 0;
  const emittedOperations = `${banner}import { z } from 'zod';\nimport { defineOperation } from './runtime.js';\n${hasReferences ? `import * as schemas from './client.${client.name}.schemas.js';` : ''}\nexport const operations = Object.freeze({${client.operations.map(emitOperation).join(',')}});`;
  const index = `${banner}export { operations } from './client.${client.name}.operations.js';\nexport { RequestValidationError } from './runtime.js';\nexport type { PreparedRequest, Responses, ProtocolResult, ProtocolFailure, ObservedResponse, HeaderContext } from './runtime.js';`;
  return {
    [`client.${client.name}.schemas.ts`]: emittedSchema,
    [`client.${client.name}.operations.ts`]: emittedOperations,
    [`client.${client.name}.ts`]: index,
  };
}

export async function render(
  descriptor: Descriptor,
  clients: readonly Client[],
): Promise<Readonly<Record<string, string>>> {
  const helper = await readFile(
    new URL('./runtime.ts', import.meta.url),
    'utf8',
  );
  const outputs: Record<string, string> = {
    'runtime.ts': `${banner}${helper}`,
  };
  for (const client of clients)
    Object.assign(outputs, renderClient(descriptor, client));
  const rendered = await Promise.all(
    Object.entries(outputs).map(async ([name, source]) => {
      // The API uses these options without discovering consumer configuration.
      // Keep generated bytes independent of cwd, plugins, and import reordering.
      const result = await format(name, source, {
        printWidth: 80,
        singleQuote: true,
        trailingComma: 'all',
        semi: true,
        endOfLine: 'lf',
        tabWidth: 2,
        useTabs: false,
        sortImports: false,
        embeddedLanguageFormatting: 'off',
      });
      // Oxfmt can resolve with errors and the original, invalid source. Reject
      // that result before any part of the complete output set reaches disk.
      if (result.errors.length > 0)
        fail(
          `generated ${name}`,
          `Oxfmt could not format TypeScript: ${result.errors.map((error) => error.message).join('; ')}`,
        );
      return [name, result.code] as const;
    }),
  );
  return Object.freeze(Object.fromEntries(rendered));
}
